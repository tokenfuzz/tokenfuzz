def _normalize_attacker_control(v: str) -> str:
    v = v.lower()
    if v == "call-order":
        v = "call-sequence"
    return v


def _is_valid_attacker_control(v: str) -> bool:
    return v in ATTACKER_CONTROLS_VALID


def _toml_value_to_str(v) -> str:
    """Normalize a scalar TOML value for string-valued runtime fields."""
    if isinstance(v, str):
        return v
    if isinstance(v, bool):
        return "1" if v else "0"
    return str(v)


class _FallbackTOMLDecodeError(ValueError):
    pass


def _strip_inline_comment(line: str) -> str:
    in_quote = False
    escaped = False
    for i, ch in enumerate(line):
        if escaped:
            escaped = False
            continue
        if ch == "\\" and in_quote:
            escaped = True
            continue
        if ch == '"':
            in_quote = not in_quote
            continue
        if ch == "#" and not in_quote:
            return line[:i]
    return line


def _split_array_items(body: str) -> list[str]:
    items: list[str] = []
    start = 0
    in_quote = False
    escaped = False
    for i, ch in enumerate(body):
        if escaped:
            escaped = False
            continue
        if ch == "\\" and in_quote:
            escaped = True
            continue
        if ch == '"':
            in_quote = not in_quote
            continue
        if ch == "," and not in_quote:
            items.append(body[start:i].strip())
            start = i + 1
    if in_quote:
        raise _FallbackTOMLDecodeError("unterminated quoted array item")
    items.append(body[start:].strip())
    return items


def _array_literal_is_closed(value: str) -> bool:
    in_quote = False
    escaped = False
    for ch in value:
        if escaped:
            escaped = False
            continue
        if ch == "\\" and in_quote:
            escaped = True
            continue
        if ch == '"':
            in_quote = not in_quote
            continue
        if ch == "]" and not in_quote:
            return True
    return False


def _parse_basic_string(value: str) -> str:
    out: list[str] = []
    i = 0
    escapes = {
        "b": "\b",
        "t": "\t",
        "n": "\n",
        "f": "\f",
        "r": "\r",
        '"': '"',
        "\\": "\\",
    }
    while i < len(value):
        ch = value[i]
        if ch != "\\":
            out.append(ch)
            i += 1
            continue
        i += 1
        if i >= len(value):
            raise _FallbackTOMLDecodeError("unterminated string escape")
        esc = value[i]
        if esc in escapes:
            out.append(escapes[esc])
            i += 1
            continue
        if esc in ("u", "U"):
            n = 4 if esc == "u" else 8
            code = value[i + 1:i + 1 + n]
            if len(code) != n or not re.match(r"^[0-9A-Fa-f]+$", code):
                raise _FallbackTOMLDecodeError(f"invalid unicode escape: \\{esc}{code}")
            out.append(chr(int(code, 16)))
            i += 1 + n
            continue
        raise _FallbackTOMLDecodeError(f"unsupported string escape: \\{esc}")
    return "".join(out)


def _parse_array_value(val: str) -> list[str]:
    if not (val.startswith("[") and val.endswith("]")):
        raise _FallbackTOMLDecodeError(f"unsupported TOML array: {val}")
    body = val[1:-1].strip()
    if body == "":
        return []
    items = []
    for part in _split_array_items(body):
        item = part.strip()
        if item == "":
            continue
        if len(item) >= 2 and item[0] == item[-1] == '"':
            items.append(_parse_basic_string(item[1:-1]))
        else:
            raise _FallbackTOMLDecodeError(f"unsupported TOML array item: {part}")
    return items


def _parse_simple_toml(text: str) -> dict:
    parsed: dict = {}
    current = parsed
    array_table_re = re.compile(r"^\s*\[\[([A-Za-z0-9_-]+)\]\]\s*$")
    section_re = re.compile(r"^\s*\[([A-Za-z0-9_-]+)\]\s*$")
    scalar_re = re.compile(r'^\s*([A-Za-z0-9_]+)\s*=\s*(.*?)\s*$')

    raw_lines = text.splitlines()
    i = 0
    while i < len(raw_lines):
        raw_line = raw_lines[i]
        i += 1
        line = _strip_inline_comment(raw_line).strip()
        if not line:
            continue
        array_table = array_table_re.match(line)
        if array_table:
            name = array_table.group(1)
            bucket = parsed.setdefault(name, [])
            if not isinstance(bucket, list):
                raise _FallbackTOMLDecodeError(
                    f"{name} used as both a table and an array of tables"
                )
            current = {}
            bucket.append(current)
            continue
        sec = section_re.match(line)
        if sec:
            current = parsed.setdefault(sec.group(1), {})
            continue
        m = scalar_re.match(line)
        if not m:
            raise _FallbackTOMLDecodeError(f"unsupported TOML line: {raw_line}")
        key, val = m.groups()
        val = val.strip()
        if val.startswith("["):
            while not _array_literal_is_closed(val):
                if i >= len(raw_lines):
                    raise _FallbackTOMLDecodeError(f"unterminated TOML array for key: {key}")
                val += "\n" + _strip_inline_comment(raw_lines[i]).strip()
                i += 1
            current[key] = _parse_array_value(val)
        elif len(val) >= 2 and val[0] == val[-1] == '"':
            current[key] = _parse_basic_string(val[1:-1])
        elif val.lower() in ("true", "false"):
            current[key] = val.lower() == "true"
        else:
            current[key] = val
    return parsed


def parse_toml(path: str | os.PathLike) -> dict:
    """Parse a target.toml."""
    with open(path, "rb") as f:
        raw = f.read()
    text = raw.decode("utf-8", errors="replace")
    if tomllib is not None:
        return tomllib.loads(text)
    return _parse_simple_toml(text)


# ─── Discovery ──────────────────────────────────────────────────────

# Directory names directly under output/ that are harness artifacts, never
# targets. bin/benchmark stages each cell as a facade repo tree containing its
# own output/<slug>/target.toml under output/benchmark/ (its default
# --bench-root). Enumerating those facades as real targets would let
# cleanup_state delete benchmark run state and let session discovery bind a
# stale cell as TARGET_ROOT.
_OUTPUT_ARTIFACT_DIRS = {"benchmark"}


def _is_file(p: Path) -> bool:
    """is_file() that falls open on OSError.

    Session discovery walks up to shared ancestors like /tmp and probes
    sibling trees it does not own (e.g. snapd's mode-0700 /tmp/snap-private-tmp).
    A permission-denied sibling must read as "not a session", not crash the
    walk. Python <3.14's is_file() propagates PermissionError.
    """
    try:
        return p.is_file()
    except OSError:
        return False


def _is_dir(p: Path) -> bool:
    """is_dir() that falls open on OSError; see _is_file."""
    try:
        return p.is_dir()
    except OSError:
        return False


def iter_target_roots(output_root: str | os.PathLike) -> Iterator[Path]:
    """Yield the canonical target-root dirs under output/, in sorted order.

    A target root is a directory holding target.toml; its slug (path relative
    to output_root) may be nested, e.g. output/samples/sample-c. The walk
    descends through container dirs (output/samples/) but never into a target
    root's own subtree, skips the benchmark artifact tree, and never follows a
    nested output/ — so a benchmark repo-root facade is excluded regardless of
    where --bench-root points.
    """
    root = Path(output_root)

    def walk(d: Path) -> Iterator[Path]:
        try:
            # Skip symlinked dirs: a benchmark repo-root facade symlinks back to
            # the source tree (which contains its own output/), so following it
            # would recurse without bound. is_dir() alone follows the link.
            entries = sorted(
                p for p in d.iterdir() if _is_dir(p) and not p.is_symlink()
            )
        except OSError:
            return
        for e in entries:
            if e.name == "output" or (d == root and e.name in _OUTPUT_ARTIFACT_DIRS):
                continue
            if _is_file(e / "target.toml"):
                yield e                # target root — do not descend
            else:
                yield from walk(e)     # container dir — recurse

    yield from walk(root)


def find_session_dir(start: str | os.PathLike) -> Optional[Path]:
    """Walk up from `start` looking for the nearest .session-env.

    Testcases live under output/<slug>/<backend>/results/scratch-N, so the
    nearest backend-local results/.session-env wins and avoids cross-backend
    races. Callers outside a results tree scan backend result directories
    below each ancestor's output tree.
    """
    p = Path(start)
    if not p.exists():
        p = Path.cwd()
    if not p.is_dir():
        p = p.parent
    try:
        cur = p.resolve()
    except OSError:
        return None
    def scan_output_tree(base: Path) -> Optional[Path]:
        out_dir = base / "output"
        if not _is_dir(out_dir):
            return None
        # Return the first real target root that carries a session.
        for target in iter_target_roots(out_dir):
            found = find_slug_session_dir(target)
            if found is not None:
                return found
        return None

    while True:
        if _is_file(cur / ".session-env"):
            return cur
        # A caller may start at output/<slug> rather than inside its results
        # tree. Resolve that target before scanning a broader ancestor whose
        # output/ directory may contain several unrelated targets.
        found = find_slug_session_dir(cur)
        if found is not None:
            return found
        found = scan_output_tree(cur)
        if found is not None:
            return found
        if cur.parent == cur:
            return None
        cur = cur.parent


def target_toml_for_session_dir(session_dir: str | os.PathLike) -> Path:
    """Return target.toml for a backend results directory."""
    d = Path(session_dir)
    return d.parent.parent / "target.toml"


def find_target_toml(start: str | os.PathLike) -> Optional[Path]:
    """Nearest ancestor target.toml, walking up from a report or results path.

    Unlike `find_session_dir`, this never falls back to scanning `output/` for
    some other target's session: a benchmark pool holds reports next to their
    own `target.toml` but carries no `.session-env`, and a scan there returns
    whichever unrelated target happens to sort first. Everything that reads a
    report's target context must resolve it the same way, or one consumer
    scores against libxml2's threat model while another quotes wolfSSL source.
    """
    cur = Path(start).absolute()
    if cur.is_file():
        cur = cur.parent
    for p in [cur, *cur.parents]:
        candidate = p / "target.toml"
        if candidate.is_file():
            return candidate
    return None


def find_benchmark_target_rev(
    start: str | os.PathLike, expected_slug: str,
) -> str:
    """Recorded target revision for an enclosing benchmark run, else "".

    A benchmark pool has no `.session-env`, but its enclosing `run.json`
    records the exact target revision. Require the target slug to match so an
    unrelated ancestor's metadata can never be borrowed.
    """
    expected = (expected_slug or "").strip()
    if not expected:
        return ""
    cur = Path(start).absolute()
    if cur.is_file():
        cur = cur.parent
    for parent in [cur, *cur.parents]:
        metadata = parent / "run.json"
        try:
            present = metadata.is_file()
        except OSError:
            return ""
        if not present:
            continue
        try:
            value = json.loads(metadata.read_text("utf-8", errors="replace"))
        except (OSError, ValueError):
            return ""
        if not isinstance(value, dict) or str(value.get("target", "")) != expected:
            return ""
        revision = str(value.get("target_sha", "") or "").strip()
        return revision
    return ""


def find_slug_session_dir(slug_dir: str | os.PathLike) -> Optional[Path]:
    """Resolve the session dir for a known output/<slug> directory.

    `find_session_dir` walks *up* from an arbitrary path; this resolves
    the other direction — caller already knows the slug dir and wants its
    .session-env. A backend-local output/<slug>/<backend>/results/
    .session-env is authoritative. With several backends present the
    lexicographically-first is returned so the choice is deterministic.
    """
    d = Path(slug_dir)
    # A results/.session-env alone does not make its parent a target backend.
    # Shared ancestors such as /tmp routinely contain that shape from other
    # concurrent runs; require the target-root marker before descending.
    if _is_file(d / "target.toml"):
        try:
            backends = sorted(d.iterdir())
        except OSError:
            return None
        for backend in backends:
            if not _is_dir(backend):
                continue
            cand = backend / "results"
            if _is_file(cand / ".session-env"):
                return cand
    return None


# ─── .session-env ──────────────────────────────────────────────────

def read_session_env(slug_dir: str | os.PathLike) -> dict[str, str]:
    """Read .session-env, returning the allowlisted KEY -> value map."""
    env_file = Path(slug_dir) / ".session-env"
    if not env_file.is_file():
        raise FileNotFoundError(f"session-env not found: {env_file}")
    out: dict[str, str] = {}
    with open(env_file, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            key, _, value = line.partition("=")
            if key in SESSION_ENV_ALLOW:
                out[key] = value
    return out


def write_session_env(
    slug_dir: str | os.PathLike,
    results: str,
    target_root: str,
    slug: str,
    rev: str,
    logdir: str,
) -> None:
    """Write a fresh .session-env (matches target_write_session_env)."""
    d = Path(slug_dir)
    d.mkdir(parents=True, exist_ok=True)
    started = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    rev_v = rev or "unknown"
    # Persist the VCS type so downstream tools (e.g. bin/severity) get the
    # authoritative decision from resumable state without re-resolving the
    # target root from output-path heuristics. Detected from the same
    # target_root the audit binds, so it cannot disagree with bin/audit.
    try:
        repo_type = detect_repo_type(target_root)
    except Exception:
        repo_type = "none"
    lines = [
        "# Written by bin/audit at session start. Sourced by bin/probe and friends.",
        f"RESULTS_DIR={results}",
        f"TARGET_ROOT={target_root}",
        f"TARGET_SLUG={slug}",
        f"TARGET_REV={rev_v}",
        f"TARGET_REPO_TYPE={repo_type}",
        f"LOGDIR={logdir}",
        f"SESSION_STARTED={started}",
    ]
    tmp_name = ""
    env_path = d / ".session-env"
    try:
        with tempfile.NamedTemporaryFile(
            "w",
            encoding="utf-8",
            dir=d,
            prefix=".session-env.",
            suffix=".tmp",
            delete=False,
        ) as f:
            tmp_name = f.name
            f.write("\n".join(lines) + "\n")
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp_name, env_path)
        # Best-effort directory fsync so the rename is durable. Both the
        # open and the fsync can fail on filesystems that do not support
        # syncing a directory fd (some networked / sandboxed mounts) — the
        # rename itself already landed, so a failure here must not abort
        # the caller (this runs at audit session start).
        try:
            fd = os.open(str(d), os.O_RDONLY)
        except OSError:
            return
        try:
            os.fsync(fd)
        except OSError:
            pass
        finally:
            os.close(fd)
    finally:
        if tmp_name:
            try:
                os.unlink(tmp_name)
            except FileNotFoundError:
                pass


# ─── git/hg/plain source detection ──────────────────────────────────

def detect_repo_type(target_root: str | os.PathLike) -> str:
    """Return git, hg, or none for a target checkout.

    A target nested under the harness repo is still a plain target unless it
    has direct VCS metadata. That avoids treating targets/foo as a git
    checkout only because /work/.git exists above it.
    """
    root = Path(target_root)
    if (root / ".hg").is_dir():
        return "hg"
    if not (root / ".git").exists():
        return "none"
    try:
        out = subprocess.run(
            ["git", "-C", str(root), "rev-parse", "--git-dir"],
            capture_output=True, text=True, timeout=10,
        )
        if out.returncode == 0:
            return "git"
    except (OSError, subprocess.TimeoutExpired):
        pass
    return "none"


def detect_rev(target_root: str | os.PathLike) -> str:
    # An empty root is "no target tree", not "the current directory". Path("")
    # is ".", so without this the harness checkout's own HEAD comes back and
    # gets published as the audited target revision.
    if not str(target_root).strip():
        return ""
    root = Path(target_root)
    repo_type = detect_repo_type(root)
    if repo_type == "git":
        try:
            out = subprocess.run(
                ["git", "-C", str(root), "rev-parse", "HEAD"],
                capture_output=True, text=True, timeout=10,
            )
            if out.returncode == 0:
                return out.stdout.strip()
        except (OSError, subprocess.TimeoutExpired):
            pass
        return ""

    if repo_type == "hg":
        try:
            out = subprocess.run(
                ["hg", "--cwd", str(root), "id", "-i"],
                capture_output=True, text=True, timeout=10,
            )
            if out.returncode == 0:
                return out.stdout.strip().rstrip("+")
        except (OSError, subprocess.TimeoutExpired):
            pass
        return ""

    if (root / ".git").exists():
        return ""

    if root.is_dir():
        return NO_REV
    return ""


def vcs_tracked_files(target_root: str | os.PathLike) -> "set[str] | None":
    """Set of VCS-tracked files under a target checkout — root-relative,
    forward-slash — or None when the target is not a git/hg checkout (or the
    VCS query fails/times out).

    Purpose: drop untracked scratch files (agent-authored PoCs and prior-run
    leftovers dropped into the target tree) from the audit source surface, so
    they never become ranked work cards. A file the project's
    own VCS does not track is not the product's source.

    "Tracked" means committed or staged/added-but-uncommitted; untracked and
    ignored files are excluded. An empty set (a checkout that tracks no files)
    is a valid answer, distinct from None.

    None means "do not filter": callers fall open and audit everything, so a
    plain-tarball target or a transient VCS hiccup never hides real source.
    Both `git ls-files` and `hg files` emit paths relative to the checkout
    root with forward slashes, matching how the source walkers key files.

    Nested checkouts count as tracked: git submodules (--recurse-submodules)
    and hg subrepos (-S) are walked so their committed source — e.g. pcre2's
    deps/sljit, which its JIT build compiles — is kept in scope. Without
    recursion the parent lists only the gitlink/subrepo directory, so the
    walker would see the nested source on disk but find no matching tracked
    entry and drop all of it.

    Paths are read as bytes and decoded with os.fsdecode (the NUL-delimited
    `-z`/`-0` output is raw, unquoted bytes). fsdecode is the same
    surrogateescape roundtrip os.walk/pathlib use for on-disk names, so a
    non-UTF-8 tracked path is preserved and still matches the walker's key —
    it is not dropped, and it never raises a decode error.
    """
    root = Path(target_root)
    repo_type = detect_repo_type(root)
    if repo_type == "git":
        cmd = ["git", "-C", str(root), "ls-files", "--recurse-submodules", "-z"]
    elif repo_type == "hg":
        cmd = ["hg", "--cwd", str(root), "files", "-S", "-0"]
    else:
        return None
    try:
        out = subprocess.run(cmd, capture_output=True, timeout=30)
    except (OSError, subprocess.SubprocessError):
        # Fall open on a VCS failure — missing binary or timeout. A tooling
        # hiccup must never hide real source.
        return None
    if out.returncode != 0:
        return None
    return {os.fsdecode(p) for p in out.stdout.split(b"\0") if p}


# ─── Seed a starter target.toml ─────────────────────────────────────

# mach is a browser-specific driver. GN is shared by browsers, JavaScript
# shells, and general native projects, so browser execution must be selected
# explicitly for GN instead of inferred from its build marker alone.
_INFERRED_BROWSER_BUILD_SYSTEMS = {"mach"}
# CMake `install(TARGETS ...)` keywords that terminate the target-name list.
# Anything after one of these is install configuration, not a target name.
_CMAKE_INSTALL_KEYWORDS = frozenset({
    "EXPORT", "ARCHIVE", "LIBRARY", "RUNTIME", "OBJECTS", "FRAMEWORK", "BUNDLE",
    "PRIVATE_HEADER", "PUBLIC_HEADER", "RESOURCE", "INCLUDES", "DESTINATION",
    "PERMISSIONS", "CONFIGURATIONS", "COMPONENT", "NAMELINK_COMPONENT",
    "NAMELINK_ONLY", "NAMELINK_SKIP", "OPTIONAL", "EXCLUDE_FROM_ALL",
    "FILE_SET", "TYPE", "CXX_MODULES_BMI",
})


def _manifest_texts(target_root: Path, filename: str, max_depth: int = 3) -> list[str]:
    """Return the text of every `filename` within `max_depth` of target_root.

    Bounded walk: prunes sanitizer build trees, VCS dirs and dependency
    caches so a seed-time scan never descends an entire source checkout.
    """
    texts: list[str] = []
    root_str = str(target_root)
    for dirpath, dirnames, filenames in os.walk(target_root):
        depth = dirpath[len(root_str):].count(os.sep)
        if depth >= max_depth:
            dirnames[:] = []
        dirnames[:] = [
            d for d in dirnames
            if not d.startswith(("build-", ".")) and d != "node_modules"
        ]
        if filename in filenames:
            try:
                texts.append(
                    Path(dirpath, filename).read_text(
                        encoding="utf-8", errors="replace")
                )
            except OSError:
                pass
    return texts


def _autotools_installed_programs(texts: Iterable[str]) -> list[str]:
    """Names from `bin_PROGRAMS` / `sbin_PROGRAMS` in automake Makefile.am text.

    Only the *installed* program primaries are read — `check_PROGRAMS` and
    `noinst_PROGRAMS` (test drivers, helpers) are deliberately excluded.
    """
    decl_re = re.compile(r"^\s*(?:bin|sbin)_PROGRAMS\s*[+:]?=\s*(.*)$")
    out: list[str] = []
    for text in texts:
        # Collapse automake backslash line-continuations first.
        joined = re.sub(r"\\\n", " ", text)
        for line in joined.splitlines():
            m = decl_re.match(line)
            if m:
                out.extend(m.group(1).split())
    return out


def _cmake_installed_executables(texts: Iterable[str]) -> list[str]:
    """Executable target names a CMake project *installs*.

    Collects `add_executable(<name> ...)` declarations and the target list
    of `install(TARGETS ...)`, then returns their intersection so test-only
    executables (declared but not installed) are not picked. Falls back to
    every declared executable when no resolvable install() target list is
    found — still derived from the tree, never a hardcoded list.
    """
    text_list = list(texts)
    exec_names: set[str] = set()
    # The trailing keyword and the `::` separator are captured so ALIAS and
    # IMPORTED forms can be dropped: they name a reference, not a binary the
    # build emits. A phantom name from `add_executable(Ns::x ALIAS x)` would
    # otherwise collide with a same-named library in install(TARGETS ...),
    # yielding a non-empty result that suppresses the fallback below.
    add_exec_re = re.compile(
        r"add_executable\s*\(\s*([A-Za-z0-9_.:-]+)(?:\s+([A-Za-z_]+))?",
        re.IGNORECASE)
    for text in text_list:
        for m in add_exec_re.finditer(text):
            name = m.group(1)
            if "::" in name or (m.group(2) or "").upper() in ("ALIAS", "IMPORTED"):
                continue
            exec_names.add(name)
    if not exec_names:
        return []
    install_re = re.compile(
        r"install\s*\(\s*TARGETS\b([^)]*)\)", re.IGNORECASE | re.DOTALL)
    installed: list[str] = []
    for text in text_list:
        for m in install_re.finditer(text):
            for tok in m.group(1).split():
                if tok.upper() in _CMAKE_INSTALL_KEYWORDS:
                    break
                if tok in exec_names:
                    installed.append(tok)
    return installed or sorted(exec_names)


def _meson_executables(texts: Iterable[str]) -> list[str]:
    """First (name) argument of every `executable(...)` call in meson.build."""
    exe_re = re.compile(
        r"\bexecutable\s*\(\s*(?:'([^']+)'|\"([^\"]+)\")", re.IGNORECASE)
    out: list[str] = []
    for text in texts:
        for m in exe_re.finditer(text):
            out.append(m.group(1) or m.group(2))
    return out


def declared_cli_names(target_root: str | os.PathLike, build_system: str) -> list[str]:
    """User-facing CLI program names the target's own build manifests declare.

    Derived at runtime from the live target tree — never a hardcoded
    per-project list, which would couple the shared harness to specific
    codebases under audit. `seed_toml` uses this only to bias its asan_bin
    guess toward the project's installed CLI when build-asan/ holds several
    instrumented executables; the free executable scan remains the fallback
    when this yields nothing (unknown build system, generated names, ...).
    """
    root = Path(target_root)
    if build_system == "autotools":
        raw = _autotools_installed_programs(_manifest_texts(root, "Makefile.am"))
    elif build_system == "cmake":
        raw = _cmake_installed_executables(_manifest_texts(root, "CMakeLists.txt"))
    elif build_system == "meson":
        raw = _meson_executables(_manifest_texts(root, "meson.build"))
    else:
        raw = []
    names: list[str] = []
    seen: set[str] = set()
    for tok in raw:
        # Strip autotools $(EXEEXT) adornment and surrounding quotes.
        tok = tok.replace("$(EXEEXT)", "").strip().strip("'\"")
        if not tok or tok in seen:
            continue
        # Reject unresolved build-system variable references and anything
        # that is not a plain program name.
        if not re.fullmatch(r"[A-Za-z0-9._-]+", tok):
            continue
        seen.add(tok)
        names.append(tok)
    return names

# ─── Threat-model seed lookup ───────────────────────────────────────────────
#
# No per-project threat-model table is bundled: a hardcoded list doesn't scale
# as targets grow and conflates a fuzz harness (a test artifact) with a real
# attacker. Every non-browser target seeds the conservative byte-only default;
# bin/suggest-threat-model (the LLM) derives the real model per target. The
# lookup below stays as a generic, optional escape hatch — an operator MAY pass
# a custom override file — but the default path resolves nothing. Browser
# targets share one structural threat model keyed off is_browser.

def _threat_models_toml_path() -> Path:
    """Resolve .agents/references/threat_models.toml relative to this file."""
    return (
        Path(__file__).resolve().parent.parent
        / ".agents" / "references" / "threat_models.toml"
    )


def threat_model_for(slug: str,
                     threat_models_path: Path | None = None) -> list[str]:
    """Return attacker_controls for `slug` from an optional override file, or [].

    No table is shipped by default, so the default path resolves nothing and
    this returns [] — the caller then uses the byte-only default and lets
    bin/suggest-threat-model (the LLM) derive the real model. Tests (and an
    operator who wants one) may pass an explicit `threat_models_path`. A
    malformed/missing file degrades to [] so seeding still proceeds.
    """
    path = threat_models_path if threat_models_path is not None else _threat_models_toml_path()
    if not path.is_file():
        return []
    try:
        parsed = parse_toml(str(path))
    except Exception:
        return []
    entry = parsed.get(slug)
    if not isinstance(entry, dict):
        return []
    controls = entry.get("attacker_controls", [])
    if not isinstance(controls, list):
        return []
    return [c for c in controls if isinstance(c, str) and c]


def attacker_controls_for_seed(slug: str, is_browser: bool,
                               threat_models_path: Path | None = None) -> list[str]:
    """Return default [threat_model].attacker_controls for a seeded target.

    Browser targets share one structural threat model. Non-browser targets
    seed the conservative byte-only default (no curated table is shipped); the
    real model is derived per target by bin/suggest-threat-model (the LLM), or
    from an explicit operator override file if one is passed.
    """
    if is_browser:
        return ["bytes", "call-sequence", "timing"]
    curated = threat_model_for(slug, threat_models_path)
    return curated if curated else ["bytes"]


# Runtime symbol each sanitizer's instrumentation links into an executable.
# `nm` reveals them; their presence confirms the binary is actually
# instrumented (not a stray host tool that landed in the build tree).
_SANITIZER_RUNTIME_MARKER = {
    "asan": "__asan_", "ubsan": "__ubsan_", "msan": "__msan_", "tsan": "__tsan_",
}


def _binary_uses_sanitizer(path: Path, sanitizer: str = "asan") -> bool:
    marker = _SANITIZER_RUNTIME_MARKER.get(sanitizer, "__asan_")
    try:
        out = subprocess.run(
            ["nm", str(path)], capture_output=True, text=True, timeout=20,
        )
    except (OSError, subprocess.TimeoutExpired):
        return False
    if out.returncode != 0:
        return False
    return marker in out.stdout


def sanitizer_binary_is_usable(
    target_root: "str | os.PathLike", sanitizer: str, path: "str | os.PathLike",
) -> bool:
    """Whether `path` is an executable instrumented for this sanitizer."""
    root = Path(target_root)
    candidate = Path(path)
    if not candidate.is_absolute():
        candidate = root / candidate
    return (
        candidate.is_file()
        and os.access(candidate, os.X_OK)
        and _binary_uses_sanitizer(candidate, sanitizer)
    )


def _find_under(asan_dir: Path, *, name: str | None = None,
                maxdepth: int = 3) -> list[Path]:
    """Equivalent to: find <asan_dir> -maxdepth <n> -type f [-name <name>]."""
    if not asan_dir.is_dir():
        return []
    out: list[Path] = []

    def walk(d: Path, depth: int) -> None:
        if depth > maxdepth:
            return
        try:
            entries = sorted(d.iterdir())
        except OSError:
            return
        for e in entries:
            if e.is_file():
                if name is None or e.name == name:
                    out.append(e)
            elif e.is_dir() and not e.is_symlink():
                walk(e, depth + 1)

    walk(asan_dir, 1)
    return out


def _is_shared_lib(name: str) -> bool:
    """A linkable shared object: lib<name>.so / .dylib, or a versioned
    SONAME (lib<name>.so.2, lib<name>.2.dylib)."""
    return name.endswith((".so", ".dylib")) or ".so." in name


# Build subdirectories that hold artifacts which are never the audited
# project's own library or CLI: CMake's CMakeFiles/ (compiler-probe
# binaries like CMakeDetermineCompilerABI_C.bin, object trees), unit-test
# frameworks vendored under test(s)/ (Unity, gtest, …), and FetchContent
# dependency builds under _deps/. Inclusion criterion: a directory a build
# system populates with helper/probe/dependency artifacts, not the target's
# primary output. Structural (no project names), target-agnostic as new
# projects appear.
_AUX_BUILD_DIRS = {"cmakefiles", "test", "tests", "_deps"}


def _is_aux_build_path(p: Path, base_dir: Path) -> bool:
    try:
        rel = p.relative_to(base_dir)
    except ValueError:
        return False
    return any(part.lower() in _AUX_BUILD_DIRS for part in rel.parts[:-1])


def _path_has_aux_component(rel_path: str) -> bool:
    """True if a target.toml-relative path string traverses a build-internal
    aux directory — used to recognise a stale/bogus <san>_bin/<san>_lib value
    (e.g. a CMakeFiles compiler probe) that detection should scrub."""
    return any(part.lower() in _AUX_BUILD_DIRS
               for part in rel_path.replace("\\", "/").split("/"))


def _pick_shared_lib(san_dir: Path, root: Path) -> str:
    """Best shared library to link a C harness against, when the build
    emits no static archive (the cmake/meson default for c-ares, pcre2,
    …). Prefer the canonical unversioned linker name (libfoo.so,
    libfoo.dylib) over its versioned SONAME siblings (libfoo.so.2,
    libfoo.2.19.4.dylib); among equals, shortest basename then path.

    Single-library convention, mirroring the static-archive heuristic
    above: ambiguous multi-library builds resolve to the first canonical
    match, which the operator can override in target.toml."""
    shared = [s for s in _find_under(san_dir, name=None)
              if _is_shared_lib(s.name) and "posix" not in s.name
              and not _is_aux_build_path(s, san_dir)]
    if not shared:
        return ""
    shared.sort(key=lambda s: (not s.name.endswith((".so", ".dylib")),
                               len(s.name), str(s)))
    return str(shared[0]).removeprefix(str(root) + "/")


def _detect_sanitizer_lib(san_dir: Path, root: Path) -> str:
    """Library a C harness must link against for the sanitizer built under
    `san_dir` (a build-<san>/ tree). Static archive preferred (the harness
    links it directly); otherwise the canonical instrumented shared object.
    Empty when the build tree is absent or ships no linkable library —
    i.e. a header-only library or a CLI-only target. Sanitizer-agnostic:
    the same archive-then-shared rule holds for asan/ubsan/msan/tsan."""
    if not san_dir.is_dir():
        return ""
    archives = [a for a in _find_under(san_dir, name=None)
                if a.suffix == ".a" and not _is_aux_build_path(a, san_dir)]
    for a in archives[:3]:
        if "posix" in a.name:
            continue
        return str(a).removeprefix(str(root) + "/")
    if archives:
        return str(archives[0]).removeprefix(str(root) + "/")
    return _pick_shared_lib(san_dir, root)


def _cli_candidates(san_dir: Path, root: Path, build_system: str,
                    sanitizer: str, limit: int) -> list[str]:
    """Up to `limit` instrumented CLI executables under `san_dir` (a
    build-<san>/ tree), best first: the CLI names the build manifests
    declare, else — only when those match nothing — the instrumented
    executables that are not a shared library, object file, or
    build-system-internal artifact (CMakeFiles/ compiler probes, test
    helpers). Empty when the build ships no CLI: a library-only or
    header-only target. The aux-dir prune is what stops a CMake compiler
    probe (CMakeDetermineCompilerABI_C.bin) being mistaken for the tool.

    The manifest pass is kept exclusive because the free scan cannot tell
    a project's own tool from the test drivers and benchmarks beside it —
    only the manifests carry that distinction."""
    if not san_dir.is_dir():
        return []
    found: list[str] = []

    def take(path: Path) -> bool:
        rel = str(path).removeprefix(str(root) + "/")
        if rel not in found:
            found.append(rel)
        return len(found) >= limit

    for cand_name in declared_cli_names(root, build_system):
        for m in _find_under(san_dir, name=cand_name):
            if (os.access(m, os.X_OK) and not _is_aux_build_path(m, san_dir)
                    and _binary_uses_sanitizer(m, sanitizer) and take(m)):
                return found
    if found:
        return found
    # Filter to plausible CLI executables BEFORE capping the nm probes:
    # CMakeFiles/ alone can hold dozens of files, so capping first would
    # exhaust the budget on pruned entries and never reach the real tool
    # (e.g. curl's build puts src/curl after a large CMakeFiles/ tree).
    def _is_cli_candidate(f: Path) -> bool:
        if _is_aux_build_path(f, san_dir) or not os.access(f, os.X_OK):
            return False
        return not (f.name.endswith((".exe", ".so", ".dylib", ".o"))
                    or "sanity" in f.name)
    candidates = [f for f in _find_under(san_dir) if _is_cli_candidate(f)]
    for f in candidates[:60]:
        if _binary_uses_sanitizer(f, sanitizer) and take(f):
            break
    return found


def _detect_cli_bin(san_dir: Path, root: Path, build_system: str,
                    sanitizer: str = "asan") -> str:
    """The single best instrumented CLI executable, or empty."""
    found = _cli_candidates(san_dir, root, build_system, sanitizer, 1)
    return found[0] if found else ""


def cli_candidates(target_root: "str | os.PathLike", sanitizer: str,
                   limit: int) -> list[str]:
    """Selectable instrumented CLIs for a sanitizer, best first.

    `_detect_cli_bin` picks the head of this list for target.toml;
    bin/suggest-runner offers the whole list to the model, because which
    installed program reads attacker-supplied input is a semantic choice
    the build manifests do not record."""
    root = Path(target_root)
    return _cli_candidates(
        _build_dir_for(root, sanitizer), root, _detect_build_system(root),
        sanitizer, limit,
    )


def detect_sanitizer_build_artifacts(
    target_root: "str | os.PathLike", sanitizer: str
) -> tuple[str, str]:
    """Return the selectable (binary, library) produced for a sanitizer."""
    root = Path(target_root)
    san_dir = _build_dir_for(root, sanitizer)
    detected = (
        _detect_cli_bin(
            san_dir, root, _detect_build_system(root), sanitizer
        ),
        _detect_sanitizer_lib(san_dir, root),
    )
    return tuple(
        _canonical_build_artifact(value, sanitizer) if value else ""
        for value in detected
    )


def detect_browser_sanitizer_bin(
    target_root: "str | os.PathLike", sanitizer: str
) -> str:
    """Return the best instrumented browser executable in a native build.

    App bundles declare their main executable in ``Info.plist``. Prefer the
    shallowest foreground product. On non-bundle layouts, accept a target-named
    product under ``dist`` or the sole executable directly in the build root.
    Ambiguity returns no answer so setup requires an explicit ``asan_bin``
    instead of silently choosing a helper. No product name is embedded here.

    Detection is a setup-time answer that setup persists; run-time callers read
    the configured field rather than repeating this scan per probe.
    """
    root = Path(target_root).absolute()
    san_dir = _build_dir_for(root, sanitizer)
    bundles: list[Path] = []
    if san_dir.is_dir():
        for dirpath, dirnames, _filenames in os.walk(san_dir):
            relative = Path(dirpath).relative_to(san_dir)
            if len(relative.parts) >= 4:
                dirnames[:] = []
                continue
            app_names = [name for name in dirnames if name.endswith(".app")]
            for app_name in app_names:
                app = Path(dirpath) / app_name
                info = app / "Contents" / "Info.plist"
                try:
                    with info.open("rb") as stream:
                        metadata = plistlib.load(stream)
                except (OSError, plistlib.InvalidFileException):
                    continue
                if not isinstance(metadata, dict):
                    continue
                if _plist_truthy(metadata.get("LSBackgroundOnly")) or \
                        _plist_truthy(metadata.get("LSUIElement")):
                    continue
                executable = metadata.get("CFBundleExecutable", "")
                if not isinstance(executable, str) or not executable:
                    continue
                candidate = app / "Contents" / "MacOS" / executable
                if sanitizer_binary_is_usable(
                    root, sanitizer, candidate
                ):
                    bundles.append(candidate)
            dirnames[:] = [
                name for name in dirnames if not name.endswith(".app")
            ]
    if bundles:
        bundles.sort(key=lambda path: (len(path.relative_to(san_dir).parts), str(path)))
        shallowest_depth = len(bundles[0].relative_to(san_dir).parts)
        shallowest = [
            path for path in bundles
            if len(path.relative_to(san_dir).parts) == shallowest_depth
        ]
        if len(shallowest) == 1:
            return _canonical_build_artifact(
                str(shallowest[0]).removeprefix(str(root) + "/"), sanitizer
            )
        return ""
    dist = san_dir / "dist"
    for candidate in _find_under(dist, name=root.name, maxdepth=8):
        if sanitizer_binary_is_usable(root, sanitizer, candidate):
            return _canonical_build_artifact(
                str(candidate).removeprefix(str(root) + "/"), sanitizer
            )
    # Ambiguity is settled on the cheap file test before any instrumentation
    # check: a build root with a dozen executables needs an explicit asan_bin
    # whichever ones are instrumented, and `nm` over each of them is minutes
    # of work on a large browser tree.
    try:
        entries = sorted(san_dir.iterdir())
    except OSError:
        entries = []
    direct = [
        candidate for candidate in entries
        if candidate.is_file() and os.access(candidate, os.X_OK)
    ]
    if len(direct) == 1 and sanitizer_binary_is_usable(
        root, sanitizer, direct[0]
    ):
        return _canonical_build_artifact(
            str(direct[0]).removeprefix(str(root) + "/"), sanitizer
        )
    return ""


def _plist_truthy(value: object) -> bool:
    """Interpret the boolean forms commonly emitted in application plists."""
    if isinstance(value, bool):
        return value
    return isinstance(value, str) and value.strip().lower() in {
        "1", "true", "yes",
    }


def _browser_executable_is_helper(path: Path) -> bool:
    """Whether an app-bundle executable is declared background-only.

    Browser builds often copy process helpers next to the primary product.
    They are valid sanitizer executables, but cannot launch a testcase as the
    browser runner. Plist role metadata distinguishes them without knowing a
    product or helper name.
    """
    for parent in path.parents:
        if parent.suffix != ".app":
            continue
        info = parent / "Contents" / "Info.plist"
        try:
            with info.open("rb") as stream:
                metadata = plistlib.load(stream)
        except (OSError, plistlib.InvalidFileException):
            return False
        if not isinstance(metadata, dict):
            return False
        return (
            _plist_truthy(metadata.get("LSBackgroundOnly"))
            or _plist_truthy(metadata.get("LSUIElement"))
        )
    return False


def _build_field_line(field: str, value: str) -> str:
    """Render a <san>_bin/<san>_lib assignment in its section's style.

    asan_* keep seed's wide alignment; the rest use the [sanitizer] block's
    short form. Cosmetic — the TOML parser ignores spacing."""
    if field in ("asan_bin", "asan_lib"):
        return f"{field}{' ' * (14 - len(field))}= {toml_basic_string(value)}"
    pad = " " * (len("ubsan_lib") - len(field))
    return f"{field}{pad} = {toml_basic_string(value)}"


def set_sanitizer_bin(text: str, sanitizer: str, value: str) -> str:
    """Point an active <san>_bin at `value`, preserving every other setting.

    Only rewrites a field that is already active: an unset binary means the
    sanitizer is not selectable, and the caller reached this path through
    one that was."""
    field = f"{sanitizer}_bin"
    field_re = re.compile(rf"^\s*{field}\b\s*=")
    lines = text.splitlines()
    for i, line in enumerate(lines):
        if field_re.match(line) and not line.lstrip().startswith("#"):
            lines[i] = _build_field_line(field, value)
            return "\n".join(lines) + "\n"
    return text


def _in_other_sanitizer_build(
    target_root: Path, sanitizer: str, candidate: Path,
) -> bool:
    """Whether `candidate` sits in a sanitizer build tree that is not this one."""
    for other in ("asan", "ubsan", "msan", "tsan"):
        if other == sanitizer:
            continue
        try:
            candidate.resolve().relative_to(
                _build_dir_for(target_root, other).resolve()
            )
            return True
        except (OSError, ValueError):
            continue
    return False


def _configured_build_field_is_usable(
    target_root: Path, sanitizer: str, field: str, value: str,
) -> bool:
    """A curated build field must still belong to the sanitizer it names."""
    candidate = _resolve_target_path(target_root, value)
    if field.endswith("_bin"):
        # A configured executable in the matching build is operator/build
        # provenance even when `nm` cannot inspect a stripped binary. An
        # absolute external executable has no such provenance, so require its
        # runtime marker before preserving it.
        try:
            candidate.resolve().relative_to(
                _build_dir_for(target_root, sanitizer).resolve()
            )
            in_matching_build = True
        except (OSError, ValueError):
            in_matching_build = False
        return (
            candidate.is_file()
            and os.access(candidate, os.X_OK)
            and (
                in_matching_build
                or sanitizer_binary_is_usable(
                    target_root, sanitizer, candidate
                )
            )
        )
    # A library the build itself does not emit — a vendored or prebuilt
    # instrumented archive — is operator provenance, and detection has nothing
    # better to offer. Only a library belonging to a *different* sanitizer is
    # a mismatch, the same failure the binary branch rejects above.
    return candidate.is_file() and not _in_other_sanitizer_build(
        target_root, sanitizer, candidate
    )


def refresh_detected_build_fields(
    target_root: Path, toml_path: Path, *, is_browser: bool = False,
) -> bool:
    """Re-detect <san>_bin and <san>_lib for every sanitizer from the build
    trees now on disk and correct them in target.toml in place. Policy per
    field: a configured value that is still a usable artifact in the matching
    sanitizer tree wins — it may have been chosen by an operator or by
    bin/suggest-runner, and detection is a weaker signal than either. Otherwise
    adopt what the build yields (filling an unset field or replacing a stale or
    mismatched one), or scrub a value that points at a build-internal artifact
    or a now-missing path. Returns True if anything changed.

    seed_toml must run before any build exists (it supplies build_system to
    the build step), so on a fresh target it cannot detect these fields and
    leaves them commented FILL_ME; on a target rebuilt under different cmake
    options a previously-detected path can also go stale. setup-target
    calls this after materializing the canonical build to repair that
    ordering — a surgical line edit, not a re-seed, so the LLM-curated
    [threat_model]/[s6_peers] survive."""
    try:
        lines = Path(toml_path).read_text(encoding="utf-8").splitlines()
    except OSError:
        return False
    changed = False

    def _value_of(line: str) -> str:
        if line.lstrip().startswith("#"):
            return ""
        m = re.search(r'=\s*"((?:[^"\\]|\\.)*)"', line)
        return m.group(1) if m else ""

    def _commented(field: str, san: str) -> str:
        # Retain FILL_ME so bin/setup-target's grep-for-FILL_ME re-seed
        # trigger keeps firing for the now-unset field.
        stem = "FILL_ME.a" if field.endswith("_lib") else "FILL_ME"
        return f'# {field} = "build-{san}/{stem}"'

    def _refresh(field: str, san: str, detected: str) -> None:
        nonlocal changed
        field_re = re.compile(rf"^\s*#?\s*{field}\b\s*=")
        for i, ln in enumerate(lines):
            if not field_re.match(ln):
                continue
            cur = _value_of(ln)
            cur_path = _resolve_target_path(target_root, cur) if cur else target_root
            cur_bogus = bool(cur) and (
                _path_has_aux_component(cur)
                or _has_physical_build_prefix(cur, san)
                or not cur_path.exists()
                or (is_browser and field.endswith("_bin")
                    and _browser_executable_is_helper(cur_path))
            )
            if (
                cur and not cur_bogus
                and (
                    cur == detected
                    or _configured_build_field_is_usable(
                        target_root, san, field, cur
                    )
                )
            ):
                return                                   # keep what is usable
            if detected:
                new_line = _build_field_line(field, detected)  # fill or correct
            elif cur:
                new_line = _commented(field, san)        # scrub unusable
            else:
                return                                   # leave unset
            if new_line != ln:
                lines[i] = new_line
                changed = True
            return

    for san in ("asan", "ubsan", "msan", "tsan"):
        if is_browser:
            detected_bin = detect_browser_sanitizer_bin(target_root, san)
            detected_lib = ""
        else:
            detected_bin, detected_lib = detect_sanitizer_build_artifacts(
                target_root, san
            )
            _refresh(f"{san}_lib", san, detected_lib)
        _refresh(f"{san}_bin", san, detected_bin)
    if changed:
        Path(toml_path).write_text("\n".join(lines) + "\n", encoding="utf-8")
    return changed


_HEADER_SUFFIXES = (".h", ".hpp", ".hh", ".hxx", ".H")


def _detect_include_dirs(target_root: Path, asan_dir_name: str) -> list[str]:
    """Return public-header search paths relative to target_root.

    Heuristic, not exhaustive — covers the layouts the seeder has observed:
      - `include/` populated with headers (curl, libxml2, openssl, ...)
      - headers at source root (cJSON, sqlite, lua, libpng, ...)
      - `src/` carrying public headers (some autotools projects)
    The `build-asan/include` entry is always emitted because CMake/Meson
    routinely generate config headers there; if the dir doesn't exist at
    repro time the -I just does nothing. `asan_dir_name` is only that
    persisted literal, so it must be the canonical alias: a container
    suffix belongs to the running image, and Config.resolve_path applies
    the current one.
    """
    out: list[str] = []

    def _has_headers(d: Path, recursive: bool = False) -> bool:
        if not d.is_dir():
            return False
        try:
            it = d.rglob("*") if recursive else d.iterdir()
            for e in it:
                if e.is_file() and e.suffix in _HEADER_SUFFIXES:
                    return True
        except OSError:
            pass
        return False

    if _has_headers(target_root / "include", recursive=True):
        out.append("include")
    if _has_headers(target_root, recursive=False):
        out.append(".")
    # `src/` is a public-header location for some autotools projects but a
    # private-only one for many others; only include it when it actually
    # has headers AND no `include/` was found, to avoid pulling private
    # internals onto the search path for projects that already publish via
    # `include/`.
    if "include" not in out and _has_headers(target_root / "src", recursive=False):
        out.append("src")
    out.append(f"{asan_dir_name}/include")
    return out


def _detect_build_system(target_root: Path) -> str:
    """Return a slug naming the dominant build/package system at target_root.

    The slug drives both `seed_toml`'s default [runner] block and
    `bin/export-repro`'s reproduce.sh template. Order matters: native-build
    systems are checked before language-ecosystem package managers because
    a polyglot tree may have Cargo+autotools (e.g. a Rust binding inside a
    C library) — the native build is the one ASan ties into.
    """
    # Native compiled systems (driver scripts first, then build files).
    if (target_root / "mach").is_file() and os.access(target_root / "mach", os.X_OK):
        return "mach"
    if (target_root / ".gn").is_file():
        return "gn"
    if (target_root / "CMakeLists.txt").is_file():
        return "cmake"
    if (target_root / "meson.build").is_file():
        return "meson"
    if (
        (target_root / "configure").is_file() and os.access(target_root / "configure", os.X_OK)
        or (target_root / "configure.ac").is_file()
        or (target_root / "autogen.sh").is_file()
    ):
        return "autotools"
    # Language ecosystems — single canonical manifest per language. The
    # order here matters only when a tree has multiple manifests; the
    # first match wins. We pick the language whose runtime is most
    # likely to drive testcases on this target.
    if (target_root / "Cargo.toml").is_file():
        return "cargo"
    if (target_root / "go.mod").is_file():
        return "go"
    if (target_root / "Package.swift").is_file():
        return "swift"
    if (target_root / "pom.xml").is_file():
        return "maven"
    if (
        (target_root / "build.gradle").is_file()
        or (target_root / "build.gradle.kts").is_file()
        or (target_root / "settings.gradle").is_file()
        or (target_root / "settings.gradle.kts").is_file()
    ):
        return "gradle"
    if (
        any(target_root.glob("*.kts"))
        or any(target_root.glob("*.kt"))
        or any(target_root.glob("src/**/*.kt"))
        or any(target_root.glob("src/**/*.kts"))
    ):
        return "kotlin"
    if (
        (target_root / "pyproject.toml").is_file()
        or (target_root / "setup.py").is_file()
        or (target_root / "setup.cfg").is_file()
    ):
        return "python"
    if (target_root / "package.json").is_file():
        return "npm"
    if (target_root / "Gemfile").is_file() or any(target_root.glob("*.gemspec")):
        return "bundler"
    if (target_root / "composer.json").is_file():
        return "composer"
    if (target_root / "DESCRIPTION").is_file():
        return "rlang"
    if (target_root / "Makefile.PL").is_file() or any(target_root.glob("*.pm")):
        return "perl"
    return ""


# ─── Per-build-system runner defaults ───────────────────────────────
#
# When seed_toml writes a target.toml for a tree with no ASan binary
# detected, it also emits a starter [runner] block driven by the
# detected build system. The mapping below names the interpreter or
# driver plus its argument template; "{TESTCASE}" is substituted at
# run time. crash_patterns are language-specific runtime diagnostic
# strings (panics, tracebacks, race-detector reports) that lib/triage.py
# treats as crash signals.
#
# This table is derived from the language registry in lib/languages.py.
# To add a new language or build_system, edit lib/languages.py — the
# registry is the single source of truth. Tests assert this dict and
# languages.runner_table() stay in sync so the silo cannot drift.
LANGUAGE_RUNNERS: dict[str, dict] = languages.runner_table()


def _java_home_candidates(home: str) -> list[Path]:
    base = Path(home)
    return [base / "bin" / "java", base / "Contents" / "Home" / "bin" / "java"]


def _java_home_for_bin(java_bin: Path) -> str:
    # .../Contents/Home/bin/java -> .../Contents/Home
    # .../bin/java               -> ...
    if java_bin.parent.name == "bin":
        return str(java_bin.parent.parent)
    return ""


def _java_is_usable(java_bin: Path) -> bool:
    if not java_bin.is_file() or not os.access(java_bin, os.X_OK):
        return False
    try:
        result = subprocess.run(
            [str(java_bin), "-version"],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            timeout=10,
        )
    except (OSError, subprocess.TimeoutExpired):
        return False
    return result.returncode == 0


def _detect_java_runner() -> tuple[str, list[str]]:
    """Return a usable Java executable and env entries, if one is discoverable."""
    for env_name in ("AUDIT_JAVA_HOME", "JAVA_HOME"):
        java_home = os.environ.get(env_name, "")
        if not java_home:
            continue
        for candidate in _java_home_candidates(java_home):
            if _java_is_usable(candidate):
                home = _java_home_for_bin(candidate)
                return str(candidate), ([f"JAVA_HOME={home}"] if home else [])

    path_java = shutil.which("java")
    if path_java:
        candidate = Path(path_java)
        if _java_is_usable(candidate):
            home = _java_home_for_bin(candidate)
            return str(candidate), ([f"JAVA_HOME={home}"] if home else [])

    return "", []


# ─── Build freshness (audit-owned lazy build) ───────────────────────
#
# bin/audit and bin/benchmark are the consumption points: they (re)build a
# stale or missing native sanitizer tree on demand so a checkout that moved
# since the last build is never audited against the wrong binary. These two
# helpers are the cheap probe and the stamp those callers and `setup-target
# --build` share. Native C/C++ builds use their canonical recipe implicitly;
# a language target can opt in with an explicit hand-authored recipe. Browser
# drivers are included when their output obeys the same clean recipe contract;
# unsupported drivers still report "skip".
NATIVE_BUILD_SYSTEMS = frozenset({
    "cmake", "autotools", "meson", "mach", "gn",
})
# VCS metadata and generated caches — never source whose change should force a
# rebuild. Pruned from the signature so a fresh .audit log or __pycache__ entry
# can't masquerade as a source edit. Still required on top of a VCS answer:
# .audit/ is untracked-but-not-ignored in a typical target, and it is rewritten
# by every build, so an unpruned VCS listing would stale each build it produced.
_FRESHNESS_PRUNE_DIRS = {".git", ".hg", ".audit", "__pycache__", "node_modules"}
_SANITIZER_BUILD_DIR_RE = re.compile(
    r"^build-(?:asan|ubsan|msan|tsan)(?:[-+].*)?$"
)
_FRESHNESS_VCS_TIMEOUT_SECONDS = 60
# A plain `git status` refreshes and rewrites .git/index under index.lock.
# Audit agents run git in the same checkout concurrently, so a probe that took
# that lock would break their commands and theirs ours. Ask for a read-only
# answer instead.
_GIT_READ_ONLY_ENV = {"GIT_OPTIONAL_LOCKS": "0"}
# Index of the path field in a `--porcelain=v2` record, by record type.
_GIT_PATH_FIELD = {"1": 8, "2": 9, "u": 10}


def build_dir_name(san: str = "asan", *, suffix: "str | None" = None) -> str:
    """Directory name of a sanitizer build, honouring AUDIT_BUILD_SUFFIX.

    Also the key the build lease is taken on, so a suffixed or alternate tree is
    locked independently of the canonical one.
    """
    if suffix is None:
        suffix = os.environ.get("AUDIT_BUILD_SUFFIX", "")
    return f"build-{san}{suffix}"


def _build_dir_for(target_root: Path, san: str) -> Path:
    return Path(target_root) / build_dir_name(san)


def _canonical_build_artifact(path: str, san: str) -> str:
    """Make a detected physical build path safe to persist in target.toml."""
    physical = build_dir_name(san)
    canonical = build_dir_name(san, suffix="")
    if path == physical:
        return canonical
    if path.startswith(physical + "/"):
        return canonical + path[len(physical):]
    return path


def _has_physical_build_prefix(path: str, san: str) -> bool:
    """Whether a persisted path names a selected build instead of its alias."""
    head = os.path.normpath(path).partition("/")[0]
    canonical = build_dir_name(san, suffix="")
    return head != canonical and (
        head.startswith(canonical + "-") or head.startswith(canonical + "+")
    )


def _resolve_target_path(target_root: str | os.PathLike, value: str) -> Path:
    """Resolve a persisted target-relative path to the active build tree."""
    path = Path(value)
    if path.is_absolute():
        return path
    norm = os.path.normpath(value)
    if norm == ".." or norm.startswith("../"):
        raise ValueError(f"target-relative path escapes TARGET_ROOT: {value}")
    suffix = os.environ.get("AUDIT_BUILD_SUFFIX", "")
    if suffix:
        head, sep, rest = norm.partition("/")
        if head in ("build-asan", "build-ubsan", "build-msan", "build-tsan"):
            norm = f"{head}{suffix}{sep}{rest}"
    return Path(target_root) / norm


def _fold_signature(kind: str, entries: list[str]) -> str:
    return hashlib.sha1(
        "\n".join([f"schema=2-{kind}", *sorted(entries)]).encode("utf-8", "surrogatepass")
    ).hexdigest()


# One stable value meaning "the VCS could not be read". It is an admission of
# ignorance, not an identity: build_write_stamp refuses to record it and
# build_freshness refuses to match it, because a stamp written while the VCS was
# down would otherwise keep matching afterwards and report a genuinely edited
# tree as fresh — the one direction freshness must never take.
_VCS_UNAVAILABLE_SIGNATURE = hashlib.sha1(b"schema=2-vcs-unavailable").hexdigest()


def _freshness_pruned(name: str) -> bool:
    return (
        name in _FRESHNESS_PRUNE_DIRS
        or bool(_SANITIZER_BUILD_DIR_RE.fullmatch(name))
    )


def _path_is_pruned(relative: str) -> bool:
    """Whether a VCS-reported path sits under a pruned directory.

    Only parent components are consulted: a *file* that happens to be named
    build-asan is source, and dropping it would err toward "fresh".
    """
    return any(_freshness_pruned(part) for part in relative.split("/")[:-1])


def _mode_tag(path: Path) -> str:
    """The one file mode bit a build can depend on: is it executable."""
    try:
        return "x" if os.lstat(path).st_mode & 0o111 else "-"
    except OSError:
        return "absent"


def _content_digest(path: Path, *, include_untracked: bool = True) -> str:
    """Identity of one path's bytes: content, link target, or absence.

    A directory here is a submodule worktree, and its own signature is what
    answers the question — the parent's status only says "something changed",
    which is the same string for every possible change inside it. Benchmark
    source identity follows tracked content recursively; build freshness keeps
    the conservative whole-working-tree policy.
    """
    try:
        if path.is_symlink():
            return "link:" + hashlib.sha1(
                os.readlink(path).encode("utf-8", "surrogatepass")
            ).hexdigest()
        if path.is_dir():
            return "sub:" + _source_state_signature(
                path, include_untracked=include_untracked,
            )
        digest = hashlib.sha1()
        with path.open("rb") as stream:
            for block in iter(lambda: stream.read(1024 * 1024), b""):
                digest.update(block)
        return digest.hexdigest()
    except OSError:
        return "absent"


def _vcs_status_records(command: list[str], environment: dict) -> "list[str] | None":
    """NUL-delimited status records, or None if the VCS could not answer.

    Retried once: a transient failure would otherwise change how identity is
    computed, and a changed *scheme* looks exactly like changed source.
    """
    for _ in (1, 2):
        try:
            completed = subprocess.run(
                command, capture_output=True,
                timeout=_FRESHNESS_VCS_TIMEOUT_SECONDS,
                env=os.environ | environment,
            )
        except (OSError, subprocess.TimeoutExpired):
            continue
        if completed.returncode == 0:
            text = completed.stdout.decode("utf-8", "surrogateescape")
            return [record for record in text.split("\0") if record]
    return None


def _git_status_records(
    root: Path, *, include_untracked: bool = True,
) -> "list[str] | None":
    command = [
        "git", "-C", str(root), "status", "--porcelain=v2", "-z",
        "--untracked-files=all" if include_untracked else "--untracked-files=no",
    ]
    if not include_untracked:
        # Extends the same rule into submodules, which `--untracked-files` does
        # not reach. Named on the command line because that overrides
        # `diff.ignoreSubmodules` and `submodule.<name>.ignore`: a checkout that
        # configures submodule content away — common on large trees — would
        # otherwise hide a tracked edit inside one and read as no drift.
        command.append("--ignore-submodules=untracked")
    return _vcs_status_records(command, _GIT_READ_ONLY_ENV)


def _hg_status_records(
    root: Path, *, include_untracked: bool = True,
) -> "list[str] | None":
    # HGPLAIN pins the output format against user config and extensions; -mard
    # is Mercurial's --untracked-files=no, listing only tracked changes.
    return _vcs_status_records(
        ["hg", "--cwd", str(root), "status", "-0"]
        + ([] if include_untracked else ["-mard"]),
        {"HGPLAIN": "1"},
    )


def _iter_status_paths(records: "list[str]") -> "list[tuple[str, str]] | None":
    """Parse `--porcelain=v2 -z` records into (metadata, path) pairs.

    One parser for both the freshness signature and drift diagnostics. Returns
    None on any layout it does not recognise, so callers fall back rather than
    guess at a half-understood record.
    """
    pairs: list[tuple[str, str]] = []
    index = 0
    while index < len(records):
        record = records[index]
        index += 1
        kind = record[:1]
        if kind == "?":
            metadata, _, path = record.partition(" ")
        elif kind in _GIT_PATH_FIELD:
            fields = record.split(" ", _GIT_PATH_FIELD[kind])
            if len(fields) <= _GIT_PATH_FIELD[kind]:
                return None
            path = fields[-1]
            metadata = " ".join(fields[:-1])
            if kind == "2":
                # `-z` puts a rename's origin in its own NUL-delimited field.
                if index >= len(records):
                    return None
                metadata = f"{metadata} orig={records[index]}"
                index += 1
        else:
            return None
        if path and not _path_is_pruned(path):
            pairs.append((metadata, path))
    return pairs


def source_changed_paths(
    target_root: "str | os.PathLike", limit: int = 20, *,
    include_untracked: bool = True,
) -> list[str]:
    """Paths the VCS currently reports as changed, for diagnostics.

    Empty for a clean checkout, and empty rather than wrong when there is no
    VCS to ask. ``include_untracked`` selects the same policy the signature was
    taken under, so the paths named always explain the value that changed.
    """
    root = Path(target_root)
    kind = detect_repo_type(root)
    if kind == "git":
        records = _git_status_records(
            root, include_untracked=include_untracked,
        )
        pairs = _iter_status_paths(records) if records is not None else None
        paths = [path for _, path in pairs] if pairs else []
    elif kind == "hg":
        records = _hg_status_records(
            root, include_untracked=include_untracked,
        )
        paths = _hg_status_paths(records) if records is not None else []
    else:
        return []
    return sorted(paths)[:limit]


def source_signature(target_root: "str | os.PathLike") -> str:
    """Content identity of a target's source tree (see _source_state_signature)."""
    return _source_state_signature(Path(target_root))


def _git_source_entries(
    root: Path, *, include_untracked: bool = True,
) -> "list[str] | None":
    """One entry per path git reports as changed, or None if git cannot answer.

    Ignored paths are absent from `git status` by construction, and that is the
    point: output a target writes into its own tree during a test run is not
    source and must not stale a build. Everything git does report is
    content-hashed, so an edit that is later reverted returns the signature to
    its original value. Renames carry their origin, and a dirty submodule
    carries the record's own oids and submodule flags.
    """
    # An empty repository has no HEAD. Its files are all untracked, so the
    # conservative policy still describes them completely; requiring a revision
    # there would report "unknown" forever and let real edits pass as unchanged.
    # Tracked-only cannot say anything without one — an empty repository tracks
    # nothing, and a git that could not answer tracks nothing we can see. Both
    # would otherwise fold to one constant, which reads as "never changed".
    rev = detect_rev(root)
    if not rev and not include_untracked:
        return None
    records = _git_status_records(root, include_untracked=include_untracked)
    if records is None:
        return None
    pairs = _iter_status_paths(records)
    if pairs is None:
        return None  # unrecognised layout: fall back, never guess
    # Only the final working-tree state: path, executable bit, content. Status
    # letters and index oids are deliberately excluded — staging a change alters
    # them without altering the bytes a build compiles, and rebuilding for that
    # is pure waste.
    return [
        f"rev\0{rev}",
        *(
            f"{path}\0{_mode_tag(root / path)}\0"
            f"{_content_digest(root / path, include_untracked=include_untracked)}"
            for _, path in pairs
        ),
    ]


def _hg_status_paths(records: list[str]) -> list[str]:
    """Paths from `hg status -0` records, which are "<code> <path>"."""
    paths = []
    for record in records:
        _, separator, path = record.partition(" ")
        if separator and path and not _path_is_pruned(path):
            paths.append(path)
    return paths


def _hg_source_entries(
    root: Path, *, include_untracked: bool = True,
) -> "list[str] | None":
    """One entry per path Mercurial reports as changed, or None if it cannot say.

    Same contract as the git path: ignored files are absent from `hg status` by
    construction, and what it does report is content-hashed. Mercurial is what
    browser-sized checkouts use, and status there answers in about a second —
    hashing the tree itself would not.
    """
    records = _hg_status_records(root, include_untracked=include_untracked)
    if records is None:
        return None
    return [
        f"rev\0{detect_rev(root)}",
        *(
            f"{path}\0{_mode_tag(root / path)}\0"
            f"{_content_digest(root / path, include_untracked=include_untracked)}"
            for path in _hg_status_paths(records)
        ),
    ]


def _vcs_source_entries(
    root: Path, *, include_untracked: bool = True,
) -> "tuple[str, list[str] | None] | None":
    """(vcs kind, entries) for a tree under version control, else None.

    Entries are None when the VCS owns the tree but could not answer — a
    different situation from having no VCS at all, and the callers treat them
    differently.
    """
    kind = detect_repo_type(root)
    if kind == "git":
        return "git", _git_source_entries(
            root, include_untracked=include_untracked,
        )
    if kind == "hg":
        return "hg", _hg_source_entries(
            root, include_untracked=include_untracked,
        )
    return None


def _walk_source_entries(root: Path) -> list[str]:
    """Content identity of every non-pruned path, for a target with no VCS.

    Without VCS metadata nothing distinguishes a generated file from a source
    file, so everything counts and a target that writes into its own tree keeps
    rebuilding. Making that target a git checkout is the fix.
    """
    entries: list[str] = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [name for name in dirnames if not _freshness_pruned(name)]
        for name in list(dirnames):
            # os.walk lists a symlinked directory here and never descends it,
            # so its target would go unhashed. Account for the link itself.
            if (Path(dirpath) / name).is_symlink():
                dirnames.remove(name)
                filenames.append(name)
        for name in filenames:
            path = Path(dirpath) / name
            entries.append(f"{os.path.relpath(path, root)}\0{_content_digest(path)}")
    return entries


def _source_state_signature(
    root: Path, *, include_untracked: bool = True,
) -> str:
    """Content identity of the source a build would compile.

    Prefers VCS state, content-hashed. Build freshness includes non-ignored
    untracked paths; benchmark identity opts out because generated testcases are
    not product source. Content identity makes both policies immune to the two
    false-staleness classes a path+mtime walk cannot tell apart: ignored output
    a target writes during a test run, and an edit that is applied and then
    reverted. Both used to force a rebuild, and on a shared checkout a rebuild
    replaces the binary a concurrent run is auditing.

    A tree with no VCS is hashed path by path instead. A checkout whose VCS
    cannot be read reports one constant "unknown" value rather than silently
    switching to that walk: a changed *scheme* is indistinguishable from changed
    source, which is enough to force a rebuild or fail a cell. Unknown is not an
    identity — it is never stamped and never matches — so it reads as stale
    until the VCS answers again.

    The schema tag makes a change of backend or of this format stale every
    existing stamp on purpose.
    """
    found = _vcs_source_entries(root, include_untracked=include_untracked)
    if found is None:
        return _fold_signature("walk", _walk_source_entries(root))
    kind, entries = found
    return _VCS_UNAVAILABLE_SIGNATURE if entries is None else _fold_signature(kind, entries)


def vcs_source_signature(
    target_root: "str | os.PathLike", *, include_untracked: bool = True,
) -> str:
    """Content identity from the VCS alone, or "" when there is no cheap answer.

    Used at benchmark boundaries, where hashing a whole checkout — gigabytes,
    for a browser target — is not affordable, and where "cannot tell" must
    never be reported as "changed". Benchmark comparability passes
    ``include_untracked=False`` because it is about product source a cell could
    have read, not testcases or output the cell generated. Added/staged files
    still count as tracked.
    """
    found = _vcs_source_entries(
        Path(target_root), include_untracked=include_untracked,
    )
    if found is None or found[1] is None:
        return ""
    return _fold_signature(found[0], found[1])


def _primary_build_recipe(root: Path, san: str) -> Path:
    name = "build.sh" if san == "asan" else f"build-{san}.sh"
    return root / ".audit" / name


def _build_recipe_digest(path: Path) -> str:
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()
    except OSError:
        return ""


def build_write_stamp(
    target_root: "str | os.PathLike",
    san: str,
    *,
    recipe_path: "str | os.PathLike | None" = None,
) -> bool:
    """Mark build-<san> as current with the source tree as of now.

    Writes build-<san>/.audit-build-stamp with the detected rev (line 1, for
    human diagnostics), a source-state signature (line 2), the producing
    recipe's digest (line 3), and a fresh build-generation token (line 4).
    The token lets a pinned benchmark distinguish two successful builds made
    from identical inputs; the first three source-derived fields cannot.
    ``recipe_path`` is explicit for non-canonical build configurations;
    canonical builds use .audit/build[-<san>].sh.
    Returns False (no-op) when the build dir does not exist."""
    root = Path(target_root)
    build_dir = _build_dir_for(root, san)
    if not build_dir.is_dir():
        return False
    rev = detect_rev(root) or ""
    sig = _source_state_signature(root)
    if sig == _VCS_UNAVAILABLE_SIGNATURE:
        # Record no identity rather than a false one. A stamp saying "unknown"
        # would keep matching the next unknown answer, and a tree edited while
        # the VCS stayed down would read as fresh — auditing the wrong binary.
        # An empty signature line reads as stale until a real one is written.
        sig = ""
    recipe = Path(recipe_path) if recipe_path is not None else \
        _primary_build_recipe(root, san)
    recipe_digest = _build_recipe_digest(recipe)
    (build_dir / ".audit-build-stamp").write_text(
        f"{rev}\n{sig}\n{recipe_digest}\n{secrets.token_hex(16)}\n",
        encoding="utf-8",
    )
    return True


def build_stamp_fields(
    target_root: "str | os.PathLike", san: str = "asan",
) -> "tuple[str, str, str] | None":
    """(rev, source signature, recipe digest) recorded for build-<san>.

    None when there is no stamp to read. Lets a caller ask *why* a build is
    stale — moved source or a changed recipe — which are different problems with
    different answers.
    """
    stamp = _build_dir_for(Path(target_root), san) / ".audit-build-stamp"
    try:
        lines = stamp.read_text(encoding="utf-8").splitlines()
    except OSError:
        return None
    if not lines:
        return None
    return (
        lines[0] if lines else "",
        lines[1] if len(lines) >= 2 else "",
        lines[2] if len(lines) >= 3 else "",
    )


def changed_build_recipe(
    target_root: "str | os.PathLike", san: str = "asan",
) -> str:
    """Return the canonical recipe path when it differs from the build stamp."""
    root = Path(target_root)
    fields = build_stamp_fields(root, san)
    recipe = _primary_build_recipe(root, san)
    if fields is not None and fields[2] and \
            fields[2] != _build_recipe_digest(recipe):
        try:
            return str(recipe.relative_to(root))
        except ValueError:
            return str(recipe)
    return ""


def build_input_key(
    target_root: "str | os.PathLike",
    san: str = "asan",
    *,
    recipe_path: "str | os.PathLike | None" = None,
) -> str:
    """Short identity of everything a build is made from.

    Names an isolated build directory, so two runs that diverge from the shared
    tree in the same way share one tree instead of each minting its own. Keyed on
    the inputs themselves — not on who asked — because a model or run id would
    duplicate identical builds, which is where build explosion starts.
    """
    root = Path(target_root)
    recipe = Path(recipe_path) if recipe_path is not None else \
        _primary_build_recipe(root, san)
    payload = f"{_source_state_signature(root)}\n{_build_recipe_digest(recipe)}"
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:10]


def build_freshness(
    target_root: "str | os.PathLike",
    san: str = "asan",
    *,
    recipe_path: "str | os.PathLike | None" = None,
) -> str:
    """Classify build-<san> against the current source tree.

    Returns one of:
      * "skip"    — not a supported native C/C++ build system: no
                    build-<san> tree is expected, so freshness is N/A and
                    the caller must not try to (re)build one.
      * "missing" — native target with no build-<san> tree yet.
      * "stale"   — the source-state signature or canonical build recipe
                    differs from the recorded stamp (an upstream pull, branch
                    switch, local edit, or recipe repair), or the stamp
                    predates this mechanism.
      * "fresh"   — build-<san> exists and the source signature still matches.

    The signature (see _source_state_signature) catches every update mode
    uniformly — VCS or not, including deletion-only changes — and errs toward
    "stale" (a needless rebuild), never toward "fresh", which would audit the
    wrong binary."""
    root = Path(target_root)
    if (_detect_build_system(root) not in NATIVE_BUILD_SYSTEMS
            and recipe_path is None):
        return "skip"
    build_dir = _build_dir_for(root, san)
    if not build_dir.is_dir():
        return "missing"
    stamp = build_dir / ".audit-build-stamp"
    if not stamp.exists():
        return "stale"  # built before stamping existed → rebuild to be safe
    try:
        stamp_lines = stamp.read_text(encoding="utf-8").splitlines()
    except OSError:
        return "stale"
    stored_sig = stamp_lines[1] if len(stamp_lines) >= 2 else ""
    if not stored_sig:
        return "stale"  # old-format (rev-only) stamp → rebuild to upgrade it
    recipe = Path(recipe_path) if recipe_path is not None else \
        _primary_build_recipe(root, san)
    current_recipe_digest = _build_recipe_digest(recipe)
    stored_recipe_digest = stamp_lines[2] if len(stamp_lines) >= 3 else ""
    # Two-line stamps predate recipe identity. Accept them once when their
    # source signature still matches; the next successful build upgrades the
    # stamp. A recorded digest, including one whose recipe was later deleted,
    # remains authoritative.
    if stored_recipe_digest and stored_recipe_digest != current_recipe_digest:
        return "stale"
    current_sig = _source_state_signature(root)
    if current_sig == _VCS_UNAVAILABLE_SIGNATURE:
        return "stale"  # cannot tell is not the same as unchanged
    return "fresh" if current_sig == stored_sig else "stale"


def language_runner_defaults(build_system: str) -> dict:
    """Return the default [runner] block for a build_system, or {}."""
    defaults = {k: (list(v) if isinstance(v, list) else v)
                for k, v in LANGUAGE_RUNNERS.get(build_system, {}).items()}
    if build_system in {"maven", "gradle", "kotlin"} and defaults:
        java_bin, java_env = _detect_java_runner()
        if java_bin:
            if build_system in {"maven", "gradle"}:
                defaults["bin"] = java_bin
            defaults["env"] = java_env
    return defaults


def browser_runner_defaults(build_system: str) -> dict:
    """Return browser launch arguments for a native browser build driver.

    Browser command lines are not standardized, but the build driver is a
    stable structural signal. Target configuration can override these args
    without teaching shared code a product slug.
    """
    if build_system == "mach":
        return {
            "args": ["--profile", "{PROFILE}", "--no-remote", "{TESTCASE}"],
        }
    if build_system == "gn":
        return {
            "args": [
                "--user-data-dir={PROFILE}",
                "--no-first-run",
                "--no-default-browser-check",
                "--headless=new",
                "--dump-dom",
                "{TESTCASE}",
            ],
        }
    return {}


def update_browser_mode(toml_path: str | os.PathLike, enabled: bool) -> bool:
    """Update only the explicit browser-mode scalar in an existing config."""
    path = Path(toml_path)
    lines = path.read_text(encoding="utf-8").splitlines()
    replacement = f'is_browser    = "{1 if enabled else 0}"'
    field = re.compile(r"^\s*is_browser\s*=")
    for index, line in enumerate(lines):
        if not field.match(line):
            continue
        if line == replacement:
            return False
        lines[index] = replacement
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        return True
    build_system = next(
        (
            index for index, line in enumerate(lines)
            if re.match(r"^\s*build_system\s*=", line)
        ),
        None,
    )
    # A top-level scalar appended after a table header belongs to that table.
    # Older hand-authored configs may omit build_system, so insert before the
    # first table rather than silently writing threat_model.is_browser.
    first_table = next(
        (
            index for index, line in enumerate(lines)
            if re.match(r"^\s*\[", line)
        ),
        len(lines),
    )
    insert_at = build_system + 1 if build_system is not None else first_table
    lines.insert(insert_at, replacement)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return True


def _detect_upstream_url(target_root: Path) -> str:
    if (target_root / ".git").is_dir():
        try:
            out = subprocess.run(
                ["git", "-C", str(target_root), "config", "--get", "remote.origin.url"],
                capture_output=True, text=True, timeout=10,
            )
            if out.returncode == 0:
                return out.stdout.strip()
        except (OSError, subprocess.TimeoutExpired):
            pass
    if (target_root / ".hg").is_dir():
        try:
            out = subprocess.run(
                ["hg", "--cwd", str(target_root), "paths", "default"],
                capture_output=True, text=True, timeout=10,
            )
            if out.returncode == 0:
                return out.stdout.strip()
        except (OSError, subprocess.TimeoutExpired):
            pass
    return ""


def seed_toml(
    target_root: str | os.PathLike,
    out_path: str | os.PathLike,
    upstream_url: str = "",
    preserve_curated: bool = False,
    browser_mode: bool | None = None,
) -> None:
    """Seed a starter target.toml — best-effort introspection.

    When ``preserve_curated`` is set and out_path already parses, the curated
    sections a fresh seed cannot re-derive — [threat_model].attacker_controls,
    the whole [s6_peers] block, and build-configuration policy — are carried
    over from the existing file
    instead of reset to the conservative default (attacker_controls) or dropped
    (s6_peers, which a plain seed never emits). bin/setup-target uses this for a
    placeholder refresh, so filling one unrelated FILL_ME never discards an
    operator's hand- or LLM-curated threat model / peer set. A full re-seed
    (--force, missing, or unparseable file) leaves it False and regenerates."""
    root = Path(target_root)
    out = Path(out_path)
    slug = root.name

    # Read the curated sections to carry forward BEFORE the template is built,
    # so the render below can substitute them in place of the seed defaults.
    preserved_controls: Optional[list[str]] = None
    preserved_s6: Optional[tuple[str, list[str]]] = None
    preserved_build_widening: Optional[bool] = None
    preserved_build_configs: list[dict] = []
    if preserve_curated and out.exists():
        try:
            _existing = parse_toml(out)
        except Exception:
            _existing = {}
        _tm = _existing.get("threat_model")
        if isinstance(_tm, dict):
            _ac = _tm.get("attacker_controls")
            if isinstance(_ac, list):
                _ac = [str(x) for x in _ac if isinstance(x, str) and x]
                if _ac:
                    preserved_controls = _ac
        _s6 = _existing.get("s6_peers")
        if isinstance(_s6, dict):
            _peers = _s6.get("peers")
            if isinstance(_peers, list):
                _peers = [str(p) for p in _peers if isinstance(p, str) and p]
                if _peers:
                    _dom = _s6.get("domain")
                    preserved_s6 = (
                        str(_dom) if isinstance(_dom, str) else "",
                        _peers,
                    )
        if isinstance(_existing.get("build_widening"), bool):
            preserved_build_widening = _existing["build_widening"]
        if isinstance(_existing.get("build_config"), list):
            preserved_build_configs = [
                dict(row) for row in _existing["build_config"]
                if isinstance(row, dict)
            ]
    # Detected up front: declared_cli_names() needs the build system to know
    # which manifest to read when biasing the asan_bin guess below.
    build_system = _detect_build_system(root)
    if browser_mode is None:
        is_browser = build_system in _INFERRED_BROWSER_BUILD_SYSTEMS
        if out.exists():
            try:
                existing_target = parse_toml(out)
            except Exception:
                existing_target = {}
            existing_mode = existing_target.get("is_browser")
            if isinstance(existing_mode, (str, int, bool)):
                is_browser = str(existing_mode).lower() in {"1", "true"}
    else:
        is_browser = browser_mode

    asan_bin = ""
    asan_lib = ""

    if is_browser:
        asan_bin = detect_browser_sanitizer_bin(root, "asan")
    else:
        # Candidate CLI names come from the target's own build manifests
        # (declared_cli_names), not a hardcoded per-project table. An
        # empty list just means we fall through to the free scan below.
        asan_bin, asan_lib = detect_sanitizer_build_artifacts(root, "asan")

    if not upstream_url:
        upstream_url = _detect_upstream_url(root)

    out.parent.mkdir(parents=True, exist_ok=True)

    upstream_v = upstream_url or "FILL_ME"
    build_system_v = build_system or "unknown"

    # When introspection finds no ASan binary or archive, emit the field
    # commented out rather than as a "FILL_ME" placeholder string. A literal
    # placeholder is indistinguishable from a real path to downstream tools
    # (bin/export-repro would copy "build-asan/FILL_ME.a" into reproduce.sh
    # verbatim). The "FILL_ME" token stays in the comment so bin/setup-target's
    # grep-for-FILL_ME refresh trigger still fires, and so a human reviewer can
    # see at a glance that the field is unset. Header-only C++ libraries
    # legitimately have no asan_lib; the commented line is the steady state
    # for those targets.
    _asan_dir_name = build_dir_name("asan", suffix="")
    asan_bin_line = (
        f"asan_bin      = {toml_basic_string(asan_bin)}" if asan_bin
        else f'# asan_bin    = "{_asan_dir_name}/FILL_ME"      '
             '# uncomment + fill: ASan-instrumented CLI used by bin/run-asan'
    )
    asan_lib_line = (
        f"asan_lib      = {toml_basic_string(asan_lib)}" if asan_lib
        else f'# asan_lib    = "{_asan_dir_name}/FILL_ME.a"    '
             '# uncomment + fill if a // HARNESS testcase links a static archive'
    )
    alternate_bin_name = "FILL_ME" if is_browser else slug

    lines = [
        "# target.toml — generated by bin/setup-target or bin/audit.",
        "# Review generated values; edit only unresolved or target-specific fields.",
        "# Paths are relative to target_root unless absolute.",
        "",
        f"target        = {toml_basic_string(slug)}",
        f"upstream_url  = {toml_basic_string(upstream_v)}",
        f"build_system  = {toml_basic_string(build_system_v)}",
        *(
            [
                "",
                "# Keep the production-like primary build and add one cached ASan",
                "# sibling that enables compatible in-tree features.",
                f"build_widening = {'true' if (preserved_build_widening if preserved_build_widening is not None else True) else 'false'}",
            ]
            if build_system in NATIVE_BUILD_SYSTEMS and not is_browser else []
        ),
        "",
        "# Direct CLI binary — what `bin/run-asan generic` runs by default:",
        asan_bin_line,
        "",
        "# C-API harness build inputs (testcases with // HARNESS: link against this):",
        asan_lib_line,
        'includes      = [' + ", ".join(
            toml_basic_string(inc)
            for inc in _detect_include_dirs(root, _asan_dir_name)
        ) + "]",
        'link_libs     = ["-lm", "-lpthread"]',
        "",
        "# Optional: cmake target name used by maintainer reproduce.sh:",
        '# cmake_target  = "xmlcatalog"',
        "",
        "# Browser target? (1 enables browser/js mode, 0 = generic)",
        f'is_browser    = "{1 if is_browser else 0}"',
        "",
        "# ── Threat model (drives lib/triage.py verdict matrix) ──────────",
        "# attacker_controls lists what an attacker can supply to the target.",
        "# A crash report's Trigger source: is compared with this set. An",
        "# outside component adds CVSS MAT:P; caller-only triggers can floor Low.",
        "#   bytes           input file/stream/packet bytes (most parsers)",
        "#   call-sequence   ordered API/script calls (browsers, JS engines,",
        "#                   plugin SDKs); call-order is accepted as a synonym",
        "#   timing          timing/scheduling control (browsers, JIT)",
        "#   race            concurrent threads/processes (servers, runtimes)",
        "#   protocol-state  multi-message protocol state (TLS, HTTP servers)",
        "#   env             environment / fs state (rare: shells, init code)",
        "#   fs-state        filesystem layout (rare: archive tools)",
        "#",
        "# Note: bytes control parsed input data, not arbitrary API parameters.",
        "# If a testcase reads a parsed field and passes it as an out-of-contract",
        "# offset/size/index/lifetime parameter, report Caller contract: violated",
        "# or Parameter control: harness-only rather than treating it as security.",
        "#",
        "# The value below is a conservative seed. For a stateful library this",
        "# byte-only default under-claims — run `bin/suggest-threat-model "
        + slug + "`",
        "# for an LLM-suggested model, or edit attacker_controls by hand.",
        "[threat_model]",
    ]
    attacker_controls = (
        preserved_controls if preserved_controls is not None
        else attacker_controls_for_seed(slug, is_browser)
    )
    # toml_basic_string escapes embedded quotes/backslashes. Default tokens are
    # clean, but a preserved value carried over from a hand-edited config may
    # contain a quote — a raw f'"{v}"' would emit invalid TOML and corrupt the
    # whole file on the next placeholder refresh.
    controls_rendered = ", ".join(toml_basic_string(v) for v in attacker_controls)
    lines.append(f"attacker_controls = [{controls_rendered}]")

    # Per-sanitizer harness-link library. ubsan/msan/tsan are detected the
    # same way as asan: scan build-<san>/ for a static archive, else the
    # canonical instrumented shared object. An operator who enables a
    # second sanitizer in `enabled` and builds build-<san>/ gets a working
    # <san>_lib without a hand-edit — and export-repro then links it just
    # like asan. When the build tree is absent (the steady state — only
    # asan is built by default) or the target is a browser (links no
    # library; harnesses drive the binary), detection returns "" and the
    # field stays a commented FILL_ME placeholder.
    def _san_lib_toml_line(san: str) -> str:
        field = f"{san}_lib"
        pad = " " * (len("ubsan_lib") - len(field))
        detected = "" if is_browser else detect_sanitizer_build_artifacts(
            root, san
        )[1]
        if detected:
            return f"{field}{pad} = {toml_basic_string(detected)}"
        return f'# {field}{pad} = "{build_dir_name(san, suffix="")}/FILL_ME.a"'

    ubsan_lib_line = _san_lib_toml_line("ubsan")
    msan_lib_line = _san_lib_toml_line("msan")
    tsan_lib_line = _san_lib_toml_line("tsan")

    # Detect whether this target should default to findings-only mode.
    # Heuristic: a non-native ecosystem (cargo/go/python/...) where we
    # did NOT find an ASan binary in build-asan/. Cargo + go targets
    # CAN run ASan (via -Zsanitizer=address / -msan), but the operator
    # opts in by editing target.toml afterwards. Native build systems
    # (cmake/meson/autotools/mach) default to ["asan"] as they did
    # before.
    _findings_only_default = (
        not is_browser
        and not asan_bin
        and build_system not in NATIVE_BUILD_SYSTEMS | {"", "unknown"}
        and build_system not in SANITIZER_RUNNER_BUILD_SYSTEMS
    )

    if _findings_only_default:
        lines += [
            "",
            "# ── Sanitizer policy ─────────────────────────────────────────",
            f"# {build_system!s} target with no ASan build detected — defaulting",
            "# to FINDINGS-ONLY mode. The audit harness runs testcases through",
            "# the [runner] block below and files diagnostics under findings/",
            "# rather than crashes/. To enable a sanitizer build, uncomment",
            "# an entry in `enabled` and point the corresponding *_bin at it.",
            "# See docs/guides/multi-language.md for the per-language picture.",
            "[sanitizer]",
            "enabled = []  # findings-only — uncomment a sanitizer to enable",
            '# enabled = ["asan"]',
            '# asan_suppressions  = "build-asan/asan-suppressions.txt"',
            '# ubsan_suppressions = "build-ubsan/ubsan-suppressions.txt"',
            '# msan_suppressions  = "build-msan/msan-suppressions.txt"',
            '# tsan_suppressions  = "build-tsan/tsan-suppressions.txt"',
            f'# ubsan_bin = "build-ubsan/{alternate_bin_name}"',
            f'# msan_bin  = "build-msan/{alternate_bin_name}"',
            f'# tsan_bin  = "build-tsan/{alternate_bin_name}"',
            ubsan_lib_line,
            msan_lib_line,
            tsan_lib_line,
            '# race      — enable for Go targets; built via `go build -race`',
        ]
    else:
        lines += [
            "",
            "# ── Sanitizer policy ─────────────────────────────────────────",
            "# enabled: which sanitizers the audit harness should run for this",
            "# target. Only ASan is on by default. Tradeoffs:",
            "#   asan   memory corruption (OOB / UAF / double-free). High signal.",
            "#   msan   reads of uninitialized memory. Recommended for self-",
            "#          contained libraries; impractical for browsers because every",
            "#          dependency (including libc++) must be MSan-instrumented.",
            "#   ubsan  undefined behaviour. Noisier — enable with a curated",
            "#          -fsanitize= check list and expect to triage false",
            "#          positives like unsigned-integer-overflow or pointer-",
            "#          overflow patterns the project considers intentional.",
            "#   tsan   data races. Highest false-positive rate in practice;",
            "#          benign atomic_relaxed and intentional racy stats counters",
            "#          will fire. Only enable with a maintained suppressions",
            "#          file for the project's threading model.",
            "#   race   Go runtime race detector. Enable for Go targets built",
            "#          with `go build -race`; emits 'WARNING: DATA RACE'.",
            "# To turn off all sanitizers and audit in findings-only mode set",
            "# `enabled = []` and configure a [runner] block below.",
            "# Per-sanitizer suppression files are appended via *_OPTIONS=",
            "# suppressions=... at runner startup. Missing files emit a warning",
            "# but do not abort.",
            "[sanitizer]",
            'enabled = ["asan"]',
            '# asan_suppressions  = "build-asan/asan-suppressions.txt"',
            '# ubsan_suppressions = "build-ubsan/ubsan-suppressions.txt"',
            '# msan_suppressions  = "build-msan/msan-suppressions.txt"',
            '# tsan_suppressions  = "build-tsan/tsan-suppressions.txt"',
            f'# ubsan_bin = "build-ubsan/{alternate_bin_name}"',
            f'# msan_bin  = "build-msan/{alternate_bin_name}"',
            f'# tsan_bin  = "build-tsan/{alternate_bin_name}"',
            ubsan_lib_line,
            msan_lib_line,
            tsan_lib_line,
        ]

    # ── [runner] block (language-agnostic invocation) ───────────────
    # Always emit a [runner] block (commented unless we have a default
    # for the detected build_system). bin/probe and bin/run-asan generic
    # use `bin` when no sanitizer binary is configured; an args-only block
    # describes how a native sanitizer CLI consumes its testcase. crash_patterns
    # is read by lib/triage.py to detect runtime crashes (panics,
    # tracebacks, race-detector reports) on top of its built-in markers.
    runner_default = (
        browser_runner_defaults(build_system)
        if is_browser else language_runner_defaults(build_system)
    )

    _toml_string = toml_basic_string  # local alias for the existing call sites

    if runner_default:
        lines += [
            "",
            "# ── Runner (language / interpreter / driver invocation) ────────",
            f"# Auto-seeded for build_system = {build_system!r}.",
            "# The tokens '{TESTCASE}' and '{PROFILE}' are substituted at",
            "# run time. crash_patterns are regex strings layered on top of",
            "# lib/triage.py's built-in language-agnostic crash markers.",
            "[runner]",
        ]
        if runner_default.get("bin"):
            lines.append(
                f'bin            = {_toml_string(runner_default["bin"])}'
            )
        lines.append(
            "args           = ["
            + ", ".join(_toml_string(a) for a in runner_default["args"])
            + "]"
        )
        if runner_default.get("env"):
            lines.append(
                "env            = ["
                + ", ".join(_toml_string(e) for e in runner_default["env"])
                + "]"
            )
        if runner_default.get("crash_patterns"):
            patterns_str = ",\n  ".join(
                _toml_string(p) for p in runner_default["crash_patterns"]
            )
            lines.append(f"crash_patterns = [\n  {patterns_str},\n]")
    else:
        lines += [
            "",
            "# ── Runner (language / interpreter / driver invocation) ────────",
            "# Uncomment and edit for a script runner, or set args alone when",
            "# the sanitizer CLI needs input flags. '{TESTCASE}' expands to the",
            "# testcase path; '{NULL_DEVICE}' expands to the platform null sink.",
            "# [runner]",
            '# bin            = "/usr/bin/env"',
            '# args           = ["python3", "{TESTCASE}"]',
            '# env            = []',
            '# crash_patterns = []',
        ]

    # Carry a curated [s6_peers] forward. A plain seed never emits this section
    # (it is added by bin/suggest-peers / hand edits), so without this a
    # placeholder refresh would silently drop the operator's peer set.
    if preserved_s6 is not None:
        domain, peers = preserved_s6
        lines += [
            "",
            "# ── S6 peers (cross-project variant mining) — preserved from prior config ──",
            "[s6_peers]",
        ]
        if domain:
            lines.append(f"domain = {toml_basic_string(domain)}")
        lines.append(
            "peers = [" + ", ".join(toml_basic_string(p) for p in peers) + "]"
        )

    # Build configurations are operator-authored coverage choices. Preserve
    # them across a placeholder refresh just like the threat model and peers.
    for row in preserved_build_configs:
        lines += ["", "[[build_config]]"]
        for key in ("name", "label"):
            if isinstance(row.get(key), str) and row[key]:
                lines.append(f"{key} = {toml_basic_string(row[key])}")
        if isinstance(row.get("widen"), bool):
            lines.append(f"widen = {'true' if row['widen'] else 'false'}")
        for key in ("flags", "features"):
            values = row.get(key)
            if isinstance(values, list) and all(isinstance(v, str) for v in values):
                lines.append(
                    f"{key} = [" + ", ".join(toml_basic_string(v) for v in values) + "]"
                )

    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


# ─── High-level Python API for python callers ─────────────────────

@dataclass
class Config:
    """Parsed and normalized target configuration."""
    slug: str = ""
    target_root: str = ""
    results_dir: str = ""
    target_rev: str = ""
    session_started: str = ""
    logdir: str = ""

    upstream_url: str = ""
    asan_bin: str = ""
    asan_lib: str = ""
    ubsan_bin: str = ""
    msan_bin: str = ""
    tsan_bin: str = ""
    ubsan_lib: str = ""
    msan_lib: str = ""
    tsan_lib: str = ""
    build_system: str = ""
    build_widening: bool = False
    build_configs: list[build_config.BuildConfig] = field(default_factory=list)
    cmake_target: str = ""
    is_browser: str = "0"

    includes: list[str] = field(default_factory=list)
    defines: list[str] = field(default_factory=list)
    link_libs: list[str] = field(default_factory=list)
    attacker_controls: list[str] = field(default_factory=list)

    # Sanitizer policy: which sanitizers this target opts into, and where to
    # find optional per-sanitizer suppression files. Defaults to ASan only
    # UNLESS the target.toml explicitly sets `enabled = []` (findings-only
    # mode, suitable for interpreted-language targets where ASan cannot run).
    sanitizers_enabled: list[str] = field(default_factory=list)
    sanitizer_suppressions: dict = field(default_factory=dict)
    sanitizer_options: dict = field(default_factory=dict)
    # True when [sanitizer].enabled was present and explicitly empty (`= []`).
    # Used to skip the default ["asan"] build — an interpreted-language target
    # has no ASan build to detect, and forcing ASan would block bin/probe at
    # startup. Absent section keeps the existing default behavior.
    sanitizers_explicitly_disabled: bool = False

    # S4 (differential testing) per-engine CLI flag sets. Keys mirror the
    # [s4_diff_pairs] section in target.toml — currently jit_off and
    # jit_eager. Empty when the target has no [s4_diff_pairs] section.
    s4_diff_pairs: dict[str, list[str]] = field(default_factory=dict)

    # S6 (cross-project variant mining) peer projects. Populated only from
    # [s6_peers] in target.toml. Empty when no peers are configured.
    s6_peers: list[str] = field(default_factory=list)
    s6_domain: str = ""

    # [runner] table — language-agnostic program invocation. `bin` selects an
    # interpreter or driver when no sanitizer binary is configured. `args`
    # also describes how a configured native sanitizer CLI consumes an input
    # when `bin` is omitted. The tokens "{TESTCASE}" and "{NULL_DEVICE}" are
    # substituted at runtime. The `env` list is a flat list
    # of "KEY=VAL" strings layered on the runtime environment.
    # `crash_patterns` is a list of regex strings that lib/triage.py
    # treats as additional crash signals (Go data races, Python panics,
    # any project-specific runtime markers). Empty list means
    # triage uses only its built-in language-agnostic patterns.
    runner_bin: str = ""
    runner_args: list[str] = field(default_factory=list)
    runner_env: list[str] = field(default_factory=list)
    runner_crash_patterns: list[str] = field(default_factory=list)

    def attacker_controls_csv(self) -> str:
        if not self.attacker_controls:
            return "bytes"
        seen: set[str] = set()
        out: list[str] = []
        for v in self.attacker_controls:
            if v in seen:
                continue
            seen.add(v)
            out.append(v)
        return ",".join(out)

    def sanitizers_enabled_csv(self) -> str:
        if not self.sanitizers_enabled:
            # Explicitly disabled: return empty CSV. Callers distinguish
            # "no sanitizer" from "default asan" via the empty string.
            return "" if self.sanitizers_explicitly_disabled else "asan"
        seen: set[str] = set()
        out: list[str] = []
        for v in self.sanitizers_enabled:
            if v in seen:
                continue
            seen.add(v)
            out.append(v)
        return ",".join(out)

    def sanitizer_is_enabled(self, name: str) -> bool:
        return name.lower() in self.sanitizers_enabled

    def sanitizer_suppressions_path(self, name: str) -> str:
        """Absolute path to the suppression file for `name`, or "" if unset.

        Caller should check existence — missing files emit a warning at
        runner startup but do not abort, so audits can proceed before a
        per-target suppression list has been authored.
        """
        p = self.sanitizer_suppressions.get(name.lower(), "")
        if not p:
            return ""
        return self.resolve_path(p)

    def sanitizer_bin(self, name: str) -> str:
        name = name.lower()
        if name == "asan":
            return self.asan_bin
        if name == "ubsan":
            return self.ubsan_bin
        if name == "msan":
            return self.msan_bin
        if name == "tsan":
            return self.tsan_bin
        return ""

    def first_executable_sanitizer(self) -> tuple[str, str] | None:
        """Return the first enabled sanitizer and executable binary path."""
        for name in self.sanitizers_enabled:
            raw = self.sanitizer_bin(name)
            if not raw:
                continue
            resolved = self.resolve_path(raw)
            if Path(resolved).is_file() and os.access(resolved, os.X_OK):
                return name, resolved
        return None

    def sanitizer_lib(self, name: str) -> str:
        name = name.lower()
        if name == "asan":
            return self.asan_lib
        if name == "ubsan":
            return self.ubsan_lib
        if name == "msan":
            return self.msan_lib
        if name == "tsan":
            return self.tsan_lib
        return ""

    def resolve_path(self, p: str) -> str:
        if not p:
            return ""
        return str(_resolve_target_path(self.target_root, p))


def _apply_attacker_controls(cfg: Config, raw: list, source_path: str) -> None:
    for item in raw:
        if not isinstance(item, str) or not item:
            continue
        norm = _normalize_attacker_control(item)
        if _is_valid_attacker_control(norm):
            cfg.attacker_controls.append(norm)
        else:
            valid = " ".join(ATTACKER_CONTROLS_VALID)
            sys.stderr.write(
                f"[target] ignored unknown attacker_controls token in {source_path}: "
                f"'{item}' (valid: {valid})\n"
            )
    if not cfg.attacker_controls:
        cfg.attacker_controls.append("bytes")


def _apply_sanitizer_section(cfg: Config, raw: dict, source_path: str) -> None:
    """Populate sanitizer policy from a [sanitizer] subtable.

    Accepts:
      enabled = ["asan", ...]              # list of sanitizer slugs
      <name>_suppressions = "path"          # path to suppression file
      <name>_options     = "key=val:..."   # extra runtime opts to append
      <name>_bin         = "path"           # per-sanitizer binary override
                                            # (asan_bin still lives top-level)
      <name>_lib         = "path"           # per-sanitizer C/C++ harness lib
                                            # (asan_lib still lives top-level)

    Unknown sanitizer slugs in `enabled` get a stderr warning and are
    dropped. If `enabled` is present and explicitly empty (`= []`), the
    loader honors it as findings-only mode — used by interpreted-language
    targets without a sanitizer build. Absent `enabled` defaults to ["asan"].
    """
    # Distinguish "key absent" from "key present but empty". Real TOML
    # parsing returns the actual list; the Python 3.10 fallback parser also
    # accepts an empty `[]`. Using a sentinel default avoids confusing
    # them with each other.
    _SENTINEL: object = object()
    raw_enabled = raw.get("enabled", _SENTINEL)
    if raw_enabled is _SENTINEL:
        # Section present but `enabled` key absent → keep the default
        # (caller will append "asan" if cfg.sanitizers_enabled ends empty).
        pass
    elif isinstance(raw_enabled, list):
        if not raw_enabled:
            cfg.sanitizers_explicitly_disabled = True
        for item in raw_enabled:
            if not isinstance(item, str) or not item:
                continue
            norm = item.lower().strip()
            if norm in SANITIZERS_VALID:
                if norm not in cfg.sanitizers_enabled:
                    cfg.sanitizers_enabled.append(norm)
            else:
                valid = " ".join(SANITIZERS_VALID)
                sys.stderr.write(
                    f"[target] ignored unknown sanitizer in {source_path}: "
                    f"'{item}' (valid: {valid})\n"
                )
    for san in SANITIZERS_VALID:
        sup_key = f"{san}_suppressions"
        if isinstance(raw.get(sup_key), str) and raw[sup_key]:
            cfg.sanitizer_suppressions[san] = raw[sup_key]
        opt_key = f"{san}_options"
        if isinstance(raw.get(opt_key), str) and raw[opt_key]:
            cfg.sanitizer_options[san] = raw[opt_key]
        bin_key = f"{san}_bin"
        if isinstance(raw.get(bin_key), str) and raw[bin_key]:
            # asan_bin is the primary top-level build field; only fill the
            # ubsan/msan/tsan/race overrides from this section. (Go's race
            # detector does not have a separate Config field — it is
            # detected from any binary's output by the runtime crash signal.)
            if san == "ubsan":
                cfg.ubsan_bin = raw[bin_key]
            elif san == "msan":
                cfg.msan_bin = raw[bin_key]
            elif san == "tsan":
                cfg.tsan_bin = raw[bin_key]
        lib_key = f"{san}_lib"
        if isinstance(raw.get(lib_key), str) and raw[lib_key]:
            # asan_lib is the primary top-level library field; non-ASan
            # libraries live under [sanitizer] so one probe run cannot
            # accidentally link an ASan archive into an MSan/TSan/UBSan build.
            if san == "ubsan":
                cfg.ubsan_lib = raw[lib_key]
            elif san == "msan":
                cfg.msan_lib = raw[lib_key]
            elif san == "tsan":
                cfg.tsan_lib = raw[lib_key]


def _apply_runner_section(cfg: Config, raw: dict, source_path: str) -> None:
    """Populate cfg.runner_* from a [runner] subtable.

    Accepts:
      bin            = "/usr/bin/python3"       # optional interpreter/driver
      args           = ["-X", "dev", "{TESTCASE}"]  # literal args (use
                                                    # "{TESTCASE}" token
                                                    # for the testcase path)
      env            = ["GORACE=halt_on_error=1"]  # env vars layered on
      crash_patterns = ["my project's crash header"]  # extra regex signals

    Unknown keys are ignored. The loader keeps all the literal strings —
    bin/probe and lib/triage.py substitute "{TESTCASE}" at run time.
    """
    if isinstance(raw.get("bin"), str) and raw["bin"]:
        cfg.runner_bin = raw["bin"]
    if isinstance(raw.get("args"), list):
        cfg.runner_args = [x for x in raw["args"] if isinstance(x, str)]
    if isinstance(raw.get("env"), list):
        cfg.runner_env = [x for x in raw["env"] if isinstance(x, str) and "=" in x]
    if isinstance(raw.get("crash_patterns"), list):
        cfg.runner_crash_patterns = [
            x for x in raw["crash_patterns"] if isinstance(x, str) and x
        ]


def load_toml_into(cfg: Config, toml_path: str | os.PathLike) -> None:
    """Parse a target.toml and populate the Config in-place.

    Handles the [threat_model] section, normalizes call-order to
    call-sequence, drops unknown tokens with a stderr warning, and defaults
    attacker_controls to ["bytes"] when empty.
    """
    parsed = parse_toml(toml_path)
    p = str(toml_path)
    cfg.attacker_controls = []
    cfg.includes = []
    cfg.defines = []
    cfg.link_libs = []
    cfg.sanitizers_enabled = []
    cfg.sanitizer_suppressions = {}
    cfg.sanitizer_options = {}
    cfg.sanitizers_explicitly_disabled = False
    cfg.s4_diff_pairs = {}
    cfg.s6_peers = []
    cfg.s6_domain = ""
    cfg.ubsan_bin = ""
    cfg.msan_bin = ""
    cfg.tsan_bin = ""
    cfg.ubsan_lib = ""
    cfg.msan_lib = ""
    cfg.tsan_lib = ""
    cfg.runner_bin = ""
    cfg.runner_args = []
    cfg.runner_env = []
    cfg.runner_crash_patterns = []
    cfg.build_widening = False
    cfg.build_configs = []
    for k, v in parsed.items():
        if k in ("target", "slug") and isinstance(v, str):
            cfg.slug = cfg.slug or v
        elif k == "upstream_url" and isinstance(v, str):
            cfg.upstream_url = v
        elif k == "asan_bin" and isinstance(v, str):
            cfg.asan_bin = v
        elif k == "asan_lib" and isinstance(v, str):
            cfg.asan_lib = v
        elif k == "cmake_target" and isinstance(v, str):
            cfg.cmake_target = v
        elif k == "build_system" and isinstance(v, str):
            cfg.build_system = v
        elif k == "build_widening" and isinstance(v, bool):
            cfg.build_widening = v
        elif k == "is_browser":
            cfg.is_browser = _toml_value_to_str(v)
        elif k == "includes" and isinstance(v, list):
            cfg.includes = [x for x in v if isinstance(x, str) and x]
        elif k == "defines" and isinstance(v, list):
            cfg.defines = [x for x in v if isinstance(x, str) and x]
        elif k == "link_libs" and isinstance(v, list):
            cfg.link_libs = [x for x in v if isinstance(x, str) and x]
        elif k == "threat_model" and isinstance(v, dict):
            ac = v.get("attacker_controls", [])
            if isinstance(ac, list):
                _apply_attacker_controls(cfg, ac, p)
        elif k == "sanitizer" and isinstance(v, dict):
            _apply_sanitizer_section(cfg, v, p)
        elif k == "runner" and isinstance(v, dict):
            _apply_runner_section(cfg, v, p)
        elif k == "s4_diff_pairs" and isinstance(v, dict):
            for pair_key, pair_val in v.items():
                if isinstance(pair_val, list):
                    cfg.s4_diff_pairs[str(pair_key)] = [
                        x for x in pair_val if isinstance(x, str) and x
                    ]
        elif k == "s6_peers" and isinstance(v, dict):
            peers = v.get("peers", [])
            if isinstance(peers, list):
                cfg.s6_peers = [x for x in peers if isinstance(x, str) and x]
            dom = v.get("domain", "")
            if isinstance(dom, str):
                cfg.s6_domain = dom
    if not cfg.attacker_controls:
        cfg.attacker_controls.append("bytes")
    # Default: ASan only — UNLESS the target.toml explicitly set
    # `[sanitizer].enabled = []`, which means findings-only mode for
    # interpreted-language / sanitizer-less targets. The
    # sanitizers_explicitly_disabled flag preserves that distinction
    # for every consumer of sanitizers_enabled.
    if not cfg.sanitizers_enabled and not cfg.sanitizers_explicitly_disabled:
        cfg.sanitizers_enabled.append("asan")

    # Existing native targets predate the field, so absence adopts the new
    # primary-preserving widened sibling. An explicit false remains an
    # operator-visible opt-out. Non-native/browser targets never synthesize it.
    if "build_widening" not in parsed:
        cfg.build_widening = cfg.build_system in NATIVE_BUILD_SYSTEMS and cfg.is_browser not in ("1", "true", "True")
    if cfg.sanitizers_explicitly_disabled:
        # Alternate configurations are ASan-only. Keeping them visible in a
        # findings-only target would mislabel runner probes as alternate work.
        cfg.build_widening = False
        cfg.build_configs = []
    else:
        cfg.build_configs = build_config.from_parsed(
            parsed.get("build_config"),
            include_widened=(
                cfg.build_widening
                and cfg.build_system in NATIVE_BUILD_SYSTEMS
                and cfg.is_browser not in ("1", "true", "True")
            ),
        )

    # Normalize any path field that was stored as an audit-machine absolute
    # path (e.g. `auto-repair-target-toml` proposed
    # `/Users/.../targets/<slug>/build-asan/lib/libfoo.a`). Downstream
    # consumers (bin/export-repro _strip_sanitizer_build_prefix, the
    # seeder's `removeprefix`) assume target_root-relative form. Leaving
    # an absolute path in cfg causes reproduce.sh to emit
    # `$build/targets/<slug>/build-asan/...` instead of
    # `$build/build-asan/...`, breaking the maintainer build.
    _strip_target_root_paths(cfg)


def _strip_target_root_paths(cfg: Config) -> None:
    """Rewrite absolute target_root-prefixed values to target_root-relative."""
    root = (cfg.target_root or "").rstrip("/")
    if not root:
        return
    prefix = root + "/"

    def _rel(value: str) -> str:
        return value[len(prefix):] if value.startswith(prefix) else value

    cfg.asan_bin = _rel(cfg.asan_bin)
    cfg.asan_lib = _rel(cfg.asan_lib)
    cfg.ubsan_bin = _rel(cfg.ubsan_bin)
    cfg.ubsan_lib = _rel(cfg.ubsan_lib)
    cfg.msan_bin = _rel(cfg.msan_bin)
    cfg.msan_lib = _rel(cfg.msan_lib)
    cfg.tsan_bin = _rel(cfg.tsan_bin)
    cfg.tsan_lib = _rel(cfg.tsan_lib)
    # link_libs may carry bare archives or source compile inputs that
    # auto-repair-target-toml dragged in. Don't touch `-l…` / `-L…` /
    # `-Wl,…` flag entries.
    cfg.link_libs = [
        _rel(item) if not item.startswith("-") else item
        for item in cfg.link_libs
    ]


def load(start: str | os.PathLike) -> Config:
    """One-shot: discover slug dir, read .session-env, parse target.toml."""
    slug_dir = find_session_dir(start)
    if slug_dir is None:
        raise FileNotFoundError(
            f"no backend results/.session-env found above: {start} "
            f"(run bin/audit first, or pass --target)"
        )
    cfg = Config()
    env = read_session_env(slug_dir)
    cfg.results_dir = env.get("RESULTS_DIR", "")
    cfg.target_root = env.get("TARGET_ROOT", "")
    cfg.slug = env.get("TARGET_SLUG", "")
    cfg.target_rev = env.get("TARGET_REV", "")
    cfg.session_started = env.get("SESSION_STARTED", "")
    cfg.logdir = env.get("LOGDIR", "")
    toml_path = target_toml_for_session_dir(slug_dir)
    if not toml_path.is_file():
        raise FileNotFoundError(f"target.toml not found: {toml_path}")
    load_toml_into(cfg, toml_path)
    return cfg
